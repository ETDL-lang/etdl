fn collect_handler_methods(tree: &EventTree) -> Vec<String> {
    let mut seen = std::collections::BTreeSet::new();
    let mut methods = Vec::new();
    for node in tree.nodes.values() {
        if let Node::Operation(op) = node {
            let name = to_pascal_case(&op.handler);
            if seen.insert(name.clone()) {
                methods.push(name);
            }
        }
    }
    methods
}

fn generate_handlers_interface(package: &str, iface_name: &str, msg_type: &str, methods: &[String]) -> String {
    let mut out = String::new();
    out.push_str("// AUTOGENERATED BY ETDL COMPILER - DO NOT EDIT DIRECTLY\n");
    out.push_str("// Implement this interface in your own (never regenerated) file; the\n");
    out.push_str("// generated orchestration calls through it and never the other way around.\n");
    out.push_str(&format!("package {package}\n\n"));
    out.push_str(&format!("type {iface_name} interface {{\n"));
    for method in methods {
        out.push_str(&format!("\t{method}(message {msg_type}) (any, error)\n"));
    }
    out.push_str("}\n");
    out
}

// ---------------------------------------------------------------------
// Workflow orchestration
// ---------------------------------------------------------------------

fn generate_workflow_file(
    doc: &EtlDocument,
    package: &str,
    fault_tree_probs: &BTreeMap<String, f64>,
) -> Result<String, String> {
    let mut out = String::new();
    out.push_str("// AUTOGENERATED BY ETDL COMPILER - DO NOT EDIT DIRECTLY\n\n");
    out.push_str(&format!("package {package}\n\n"));

    // `time` is only used by a retry-policy operation's timeout
    // (`{n}*time.Second`) — Go errors on an unused import, so a document
    // with no retried operations anywhere (e.g. a barrier-only tree) must
    // not import it at all.
    let any_retry = doc
        .event_trees
        .values()
        .flat_map(|t| t.nodes.values())
        .any(|n| matches!(n, Node::Operation(op) if op.retry_policy.is_some()));

    out.push_str("import (\n");
    out.push_str(&format!("\tetdlruntime \"{GO_MODULE}/etdl/runtime\"\n"));
    if any_retry {
        out.push_str("\t\"time\"\n");
    }
    out.push_str(")\n\n");

    // ECEL `in`/`matches` (core spec Section 6) lower to a native call
    // returning `(bool, error)` (Go's idiomatic error handling), but a
    // barrier condition needs a plain `bool` usable directly inside `if
    // <cond> {` — these wrap that, panicking on the (expected-never, since
    // ECEL conditions are already type-checked at compile time) error
    // case, matching the `regexp.MustCompile`-style "this cannot fail
    // given how it's called" Go idiom.
    out.push_str("func mustMatches(value, pattern string) bool {\n");
    out.push_str("\tok, err := etdlruntime.Matches(value, pattern)\n");
    out.push_str("\tif err != nil {\n\t\tpanic(err)\n\t}\n\treturn ok\n}\n\n");
    out.push_str("func mustContains(haystack any, needle any) bool {\n");
    out.push_str("\tok, err := etdlruntime.Contains(haystack, needle)\n");
    out.push_str("\tif err != nil {\n\t\tpanic(err)\n\t}\n\treturn ok\n}\n\n");

    out.push_str(&generate_fault_tree_constants(doc, fault_tree_probs));

    for tree in doc.event_trees.values() {
        let function = generate_event_tree_function(doc, tree, fault_tree_probs)?;
        out.push_str(&function);
        out.push('\n');
    }

    Ok(out)
}

fn generate_fault_tree_constants(doc: &EtlDocument, fault_tree_probs: &BTreeMap<String, f64>) -> String {
    let mut output = String::new();
    for tree in doc.event_trees.values() {
        for (node_id, node) in &tree.nodes {
            if let Node::Operation(op) = node {
                if let Some(ref ps) = op.on_failure_probability_source {
                    if let Some((ft_id, prob)) = find_fault_tree_prob(ps, fault_tree_probs) {
                        output.push_str(&format!(
                            "// Computed from faultTrees.{ft_id}.topEvent at build time (Section 5.16)\n"
                        ));
                        let const_name = to_pascal_case(&format!("{node_id}_failure_probability"));
                        output.push_str(&format!("const {const_name} = {prob:.6}\n\n"));
                    }
                }
            }
        }
    }
    output
}

fn find_fault_tree_prob(
    ps: &etdl_parser::ast::InternalRef,
    fault_tree_probs: &BTreeMap<String, f64>,
) -> Option<(String, f64)> {
    let ft_id = extract_ft_id(&ps.pointer);
    fault_tree_probs.get(&ft_id).map(|&v| (ft_id.clone(), v))
}

fn extract_ft_id(pointer: &str) -> String {
    pointer
        .trim_start_matches("#/faultTrees/")
        .trim_end_matches("/topEvent")
        .to_string()
}

fn generate_event_tree_function(
    doc: &EtlDocument,
    tree: &EventTree,
    fault_tree_probs: &BTreeMap<String, f64>,
) -> Result<String, String> {
    let mut out = String::new();

    let tree_id = tree_id_of(doc, tree);
    let iface_name = format!("{}Handlers", to_pascal_case(&sanitize_ident(tree_id)));
    let function_name = format!("Handle{}", to_pascal_case(&sanitize_ident(&tree.initiating_event.id)));
    let msg_type = ref_to_type_name(&tree.initiating_event.message);

    out.push_str(&format!(
        "func {function_name}(message {msg_type}, publisher etdlruntime.Publisher, handlers {iface_name}) error {{\n"
    ));

    let first_barrier = find_first_barrier(tree);
    let monitor_name = first_barrier.map(to_camel_case).unwrap_or_else(|| "monitor".to_string());
    out.push_str(&format!(
        "\t{monitor_name}, err := etdlruntime.NewBranchMonitor(\"{}\")\n",
        first_barrier.unwrap_or("root")
    ));
    out.push_str("\tif err != nil {\n\t\treturn err\n\t}\n");
    out.push_str(&format!("\tdefer {monitor_name}.Close()\n\n"));

    let start_node_id = &tree.initiating_event.next;
    let body = generate_node_code(doc, tree, start_node_id, 1, fault_tree_probs, &monitor_name)?;
    out.push_str(&body);

    out.push_str("}\n");
    Ok(out)
}

fn find_first_barrier(tree: &EventTree) -> Option<&str> {
    let mut current = &tree.initiating_event.next;
    loop {
        match tree.nodes.get(current.as_str()) {
            Some(Node::Barrier(_)) => return Some(current.as_str()),
            Some(Node::Operation(op)) => current = &op.next,
            Some(Node::Consequence(_)) => return None,
            None => return None,
        }
    }
}

/// Every path this (and the functions it calls) generates always ends in
/// a `return` statement — required so the enclosing Go function (declared
/// `... error`) always compiles regardless of how deeply barriers/
/// operations nest, since Go (unlike Java/Python/C#, which tolerate a
/// function body that "falls off the end" of a void method) requires
/// every path through a function with a return type to explicitly return.
fn generate_node_code(
    doc: &EtlDocument,
    tree: &EventTree,
    node_id: &str,
    depth: usize,
    fault_tree_probs: &BTreeMap<String, f64>,
    monitor_name: &str,
) -> Result<String, String> {
    let node = tree
        .nodes
        .get(node_id)
        .ok_or_else(|| format!("node '{node_id}' not found"))?;

    match node {
        Node::Barrier(barrier) => {
            generate_barrier_code(tree, node_id, barrier, depth, doc, fault_tree_probs, monitor_name)
        }
        Node::Operation(op) => {
            generate_operation_code(tree, node_id, op, depth, doc, fault_tree_probs, monitor_name)
        }
        Node::Consequence(cons) => generate_consequence_code(cons, depth),
    }
}

fn generate_barrier_code(
    tree: &EventTree,
    node_id: &str,
    barrier: &etdl_parser::ast::Barrier,
    depth: usize,
    doc: &EtlDocument,
    fault_tree_probs: &BTreeMap<String, f64>,
    monitor_name: &str,
) -> Result<String, String> {
    let indent = "\t".repeat(depth);
    let mut output = String::new();
    let mut ends_with_default = false;

    for (i, branch) in barrier.branches.iter().enumerate() {
        let is_default = branch.condition == Condition::Default;
        if is_default {
            ends_with_default = true;
        }

        if i == 0 {
            if is_default {
                emit_branch_record(&indent, monitor_name, branch, node_id, fault_tree_probs, &mut output);
                let body = generate_node_code(doc, tree, &branch.next, depth, fault_tree_probs, monitor_name)?;
                output.push_str(&body);
                break;
            }
            let cond = condition_to_go_code(&branch.condition);
            output.push_str(&format!("{indent}if {cond} {{\n"));
        } else if is_default {
            output.push_str(&format!("{indent}}} else {{\n"));
        } else {
            let cond = condition_to_go_code(&branch.condition);
            output.push_str(&format!("{indent}}} else if {cond} {{\n"));
        }

        if !is_default || i > 0 {
            emit_branch_record(&format!("{indent}\t"), monitor_name, branch, node_id, fault_tree_probs, &mut output);
            let body = generate_node_code(doc, tree, &branch.next, depth + 1, fault_tree_probs, monitor_name)?;
            output.push_str(&body);
        }
    }

    if !(barrier.branches.len() == 1 && ends_with_default) {
        if ends_with_default {
            output.push_str(&format!("{indent}}}\n"));
        } else {
            // No `default` branch declared: emit a defensive fallthrough so
            // every path still returns (Go requires it; ETDL's own
            // validation, not this target, is responsible for whether an
            // undeclared-default barrier is otherwise well-formed).
            output.push_str(&format!("{indent}}} else {{\n"));
            output.push_str(&format!(
                "{indent}\treturn etdlruntime.NewWorkflowError(\"no barrier branch matched for node \\\"{node_id}\\\"\")\n"
            ));
            output.push_str(&format!("{indent}}}\n"));
        }
    }

    Ok(output)
}

fn emit_branch_record(
    indent: &str,
    monitor_name: &str,
    branch: &etdl_parser::ast::Branch,
    node_id: &str,
    fault_tree_probs: &BTreeMap<String, f64>,
    output: &mut String,
) {
    if let Some(p) = get_branch_prob(branch, node_id, fault_tree_probs) {
        output.push_str(&format!(
            "{indent}if err := {monitor_name}.RecordBranch(\"{}\", {p:.6}); err != nil {{\n",
            branch.outcome
        ));
        output.push_str(&format!("{indent}\treturn err\n"));
        output.push_str(&format!("{indent}}}\n"));
    }
}

fn get_branch_prob(
    branch: &etdl_parser::ast::Branch,
    _node_id: &str,
    fault_tree_probs: &BTreeMap<String, f64>,
) -> Option<f64> {
    if let Some(ref ps) = branch.probability_source {
        let ft_id = extract_ft_id(&ps.pointer);
        return fault_tree_probs.get(&ft_id).copied();
    }
    branch.effective_probability()
}

fn generate_operation_code(
    tree: &EventTree,
    node_id: &str,
    op: &etdl_parser::ast::Operation,
    depth: usize,
    doc: &EtlDocument,
    fault_tree_probs: &BTreeMap<String, f64>,
    monitor_name: &str,
) -> Result<String, String> {
    let indent = "\t".repeat(depth);
    let mut output = String::new();

    let handler_name = to_pascal_case(&op.handler);
    let timeout_s = op.timeout_ms.unwrap_or(5000) as f64 / 1000.0;

    // Suffixes every local this operation declares in the *enclosing*
    // scope (not the ones already self-scoped by an `if x := ...; ...`
    // init clause) with the node id — `op.next` chaining straight into
    // another Operation node (rather than through a nested barrier/
    // consequence block) would otherwise redeclare `_result`/`opErr`/
    // `retry` a second time in the very same Go scope, which is a compile
    // error ("no new variables on left side of :="), not merely a shadow,
    // unlike Java/Python/C#.
    let suffix = to_pascal_case(&sanitize_ident(node_id));
    let result_var = format!("result{suffix}");
    let op_err_var = format!("opErr{suffix}");
    let retry_var = format!("retry{suffix}");
    let retry_err_var = format!("retryErr{suffix}");

    if let Some(ref retry) = op.retry_policy {
        let strategy = match retry.backoff_strategy.as_ref().unwrap_or(&AstBackoffStrategy::Fixed) {
            AstBackoffStrategy::Exponential => "etdlruntime.BackoffExponential",
            AstBackoffStrategy::Fixed => "etdlruntime.BackoffFixed",
        };
        output.push_str(&format!(
            "{indent}{retry_var}, {retry_err_var} := etdlruntime.NewRetryPolicy({}, {}, {strategy})\n",
            retry.max_attempts, retry.backoff_ms
        ));
        output.push_str(&format!(
            "{indent}if {retry_err_var} != nil {{\n{indent}\treturn {retry_err_var}\n{indent}}}\n"
        ));
        output.push_str(&format!("{indent}defer {retry_var}.Close()\n"));
        output.push_str(&format!(
            "{indent}{result_var}, {op_err_var} := {retry_var}.Execute(func() (any, error) {{ return handlers.{handler_name}(message) }}, {timeout_s}*time.Second)\n"
        ));
    } else {
        output.push_str(&format!(
            "{indent}{result_var}, {op_err_var} := handlers.{handler_name}(message)\n"
        ));
    }

    // Go errors ("declared and not used") if `op.next` turns out to be a
    // `terminate` consequence or another node that never actually
    // reaches `{result_var}` — unlike Java/Python/C#, where a locally
    // unused value is merely a lint warning, not a compile error. This
    // unconditional no-op read keeps it "used" regardless of what the
    // branches below do with it.
    output.push_str(&format!("{indent}_ = {result_var}\n"));

    output.push_str(&format!("{indent}if {op_err_var} != nil {{\n"));

    if let Some(ref ps) = op.on_failure_probability_source {
        let const_name = to_pascal_case(&format!("{node_id}_failure_probability"));
        let prob_exists = find_fault_tree_prob(ps, fault_tree_probs).is_some();
        if prob_exists {
            output.push_str(&format!(
                "{indent}\tp := {const_name}\n{indent}\tif err := {monitor_name}.RecordFailure(\"{node_id}\", {op_err_var}, &p); err != nil {{\n{indent}\t\treturn err\n{indent}\t}}\n"
            ));
        } else {
            output.push_str(&format!(
                "{indent}\tif err := {monitor_name}.RecordFailure(\"{node_id}\", {op_err_var}, nil); err != nil {{\n{indent}\t\treturn err\n{indent}\t}}\n"
            ));
        }
    }

    if let Some(ref on_failure_id) = op.on_failure {
        match tree.nodes.get(on_failure_id) {
            Some(Node::Consequence(cons)) => {
                emit_send(cons, "message", &format!("{indent}\t"), &mut output);
            }
            _ => {
                let body = generate_node_code(doc, tree, on_failure_id, depth + 1, fault_tree_probs, monitor_name)?;
                output.push_str(&body);
            }
        }
    } else {
        output.push_str(&format!("{indent}\treturn {op_err_var}\n"));
    }
    output.push_str(&format!("{indent}}}\n"));

    if op.on_failure.is_some() {
        if let Some(ref ps) = op.on_failure_probability_source {
            let const_name = to_pascal_case(&format!("{node_id}_failure_probability"));
            let prob_exists = find_fault_tree_prob(ps, fault_tree_probs).is_some();
            if prob_exists {
                let prob_var = format!("prob{suffix}");
                output.push_str(&format!(
                    "{indent}{prob_var} := {const_name}\n{indent}if err := {monitor_name}.RecordSuccess(\"{node_id}\", &{prob_var}); err != nil {{\n{indent}\treturn err\n{indent}}}\n"
                ));
            } else {
                output.push_str(&format!(
                    "{indent}if err := {monitor_name}.RecordSuccess(\"{node_id}\", nil); err != nil {{\n{indent}\treturn err\n{indent}}}\n"
                ));
            }
        }
    }

    let next_node = tree.nodes.get(&op.next);
    match next_node {
        Some(Node::Consequence(cons)) => {
            emit_send(cons, &result_var, &indent, &mut output);
        }
        Some(_) => {
            let body = generate_node_code(doc, tree, &op.next, depth, fault_tree_probs, monitor_name)?;
            output.push_str(&body);
        }
        None => {
            output.push_str(&format!("{indent}return nil\n"));
        }
    }

    Ok(output)
}

fn emit_send(cons: &etdl_parser::ast::Consequence, payload_expr: &str, indent: &str, output: &mut String) {
    match cons.consequence_operation {
        etdl_parser::ast::ConsequenceOperation::Send => {
            if let Some(ref channel_ref) = cons.channel {
                let channel_name = channel_ref_name(channel_ref);
                output.push_str(&format!(
                    "{indent}return publisher.Publish(\"{channel_name}\", {payload_expr})\n"
                ));
                return;
            }
            output.push_str(&format!("{indent}return nil\n"));
        }
        etdl_parser::ast::ConsequenceOperation::Terminate => {
            output.push_str(&format!("{indent}return nil\n"));
        }
    }
}

fn generate_consequence_code(cons: &etdl_parser::ast::Consequence, depth: usize) -> Result<String, String> {
    let indent = "\t".repeat(depth);
    let mut output = String::new();
    emit_send(cons, "message", &indent, &mut output);
    Ok(output)
}

fn channel_ref_name(channel_ref: &ChannelRef) -> String {
    match channel_ref {
        ChannelRef::External(ext_ref) => extract_last_segment(&ext_ref.pointer),
        ChannelRef::Bare(name) => name.clone(),
    }
}

// ---------------------------------------------------------------------
// ECEL condition -> Go
// ---------------------------------------------------------------------

fn condition_to_go_code(condition: &Condition) -> String {
    match condition {
        Condition::Default => "true".to_string(),
        Condition::Comparison(cmp) => {
            use ecel::Comparator as C;
            match cmp.op {
                C::In => {
                    let left = path_or_literal(&cmp.left);
                    let right = array_or_literal(&cmp.right);
                    format!("mustContains({right}, {left})")
                }
                C::Matches => {
                    let left = operand_to_path_expr_or_literal(&cmp.left);
                    let right = literal_to_val_str(&literal_of(&cmp.right));
                    format!("mustMatches({left}, {right})")
                }
                _ => {
                    let (left_path, has_wildcard) = build_path_expression(&cmp.left);
                    let right = operand_to_val_str(&cmp.right);
                    let op = comparator_str(&cmp.op);

                    if has_wildcard {
                        // An immediately-invoked func literal ranging over
                        // the (concretely typed) slice — `item`'s type is
                        // inferred by `range` from the slice element type,
                        // so this needs no generics or type-name tracking,
                        // unlike a hypothetical `allMatch[T any](...)`
                        // helper would.
                        format!(
                            "func() bool {{ for _, item := range {} {{ if !(item{} {} {}) {{ return false }} }}; return true }}()",
                            left_path.path_prefix, left_path.remaining_path, op, right
                        )
                    } else {
                        let l = if left_path.path_prefix.is_empty() && left_path.remaining_path.is_empty() {
                            operand_to_val_str(&cmp.left)
                        } else {
                            left_path.path_prefix + &left_path.remaining_path
                        };
                        let r = if right.is_empty() { operand_to_path_expr(&cmp.right) } else { right };
                        format!("{l} {op} {r}")
                    }
                }
            }
        }
    }
}

fn path_or_literal(operand: &ecel::Operand) -> String {
    match operand {
        ecel::Operand::Path(_) => operand_to_path_expr(operand),
        ecel::Operand::Literal(lit) => literal_to_val_str(lit),
    }
}

fn array_or_literal(operand: &ecel::Operand) -> String {
    match operand {
        ecel::Operand::Path(_) => operand_to_path_expr(operand),
        ecel::Operand::Literal(lit) => literal_to_val_str(lit),
    }
}

fn operand_to_path_expr_or_literal(operand: &ecel::Operand) -> String {
    match operand {
        ecel::Operand::Path(_) => operand_to_path_expr(operand),
        ecel::Operand::Literal(lit) => literal_to_val_str(lit),
    }
}

fn literal_of(operand: &ecel::Operand) -> ecel::Literal {
    match operand {
        ecel::Operand::Literal(lit) => lit.clone(),
        ecel::Operand::Path(_) => ecel::Literal::String(String::new()),
    }
}

struct PathParts {
    path_prefix: String,
    remaining_path: String,
}

/// Go analog of the other targets' path-expression builder. Segments
/// render as PascalCase field access (`.Field`) — generated `struct`
/// fields are exported (capitalized), matching Go's requirement that
/// `encoding/json` can only see exported fields — and `Index`/`QuotedKey`
/// segments render as `[...]` subscripting (works on both `[]T` and
/// `map[string]any` directly).
fn build_path_expression(operand: &ecel::Operand) -> (PathParts, bool) {
    match operand {
        ecel::Operand::Path(path_expr) => {
            let segments = &path_expr.segments;
            let mut pre_wildcard = Vec::new();
            let mut post_wildcard = Vec::new();
            let mut has_wildcard = false;

            for (i, seg) in segments.iter().enumerate() {
                if i == 0 {
                    continue;
                }
                if has_wildcard {
                    post_wildcard.push(seg.clone());
                } else if matches!(seg, ecel::PathSegment::Wildcard) {
                    has_wildcard = true;
                } else {
                    pre_wildcard.push(seg.clone());
                }
            }

            let mut prefix = String::from("message");
            for seg in &pre_wildcard {
                append_segment(&mut prefix, seg);
            }

            let mut suffix = String::new();
            for seg in &post_wildcard {
                append_segment(&mut suffix, seg);
            }

            (
                PathParts { path_prefix: prefix, remaining_path: suffix },
                has_wildcard,
            )
        }
        ecel::Operand::Literal(_) => (
            PathParts { path_prefix: String::new(), remaining_path: String::new() },
            false,
        ),
    }
}

fn append_segment(out: &mut String, seg: &ecel::PathSegment) {
    match seg {
        ecel::PathSegment::Field(name) => {
            out.push('.');
            out.push_str(&to_pascal_case(name));
        }
        ecel::PathSegment::Index(idx) => {
            out.push_str(&format!("[{idx}]"));
        }
        ecel::PathSegment::QuotedKey(name) => {
            out.push_str(&format!("[\"{name}\"]"));
        }
        _ => {}
    }
}

fn operand_to_path_expr(operand: &ecel::Operand) -> String {
    match operand {
        ecel::Operand::Path(path) => {
            let mut out = String::from("message");
            for seg in path.segments.iter().skip(1) {
                if matches!(seg, ecel::PathSegment::Wildcard) {
                    continue;
                }
                append_segment(&mut out, seg);
            }
            out
        }
        ecel::Operand::Literal(_) => String::new(),
    }
}

fn operand_to_val_str(operand: &ecel::Operand) -> String {
    match operand {
        ecel::Operand::Path(_) => "".to_string(),
        ecel::Operand::Literal(lit) => literal_to_val_str(lit),
    }
}

fn literal_to_val_str(lit: &ecel::Literal) -> String {
    match lit {
        ecel::Literal::Number(n) => n.to_string(),
        ecel::Literal::String(s) => format!("\"{s}\""),
        ecel::Literal::Bool(b) => b.to_string(),
        ecel::Literal::Null => "nil".to_string(),
        ecel::Literal::Array(items) => {
            let inner: Vec<String> = items.iter().map(literal_to_val_str).collect();
            format!("[]any{{ {} }}", inner.join(", "))
        }
    }
}

fn comparator_str(op: &ecel::Comparator) -> &str {
    match op {
        ecel::Comparator::Eq => "==",
        ecel::Comparator::Neq => "!=",
        ecel::Comparator::Gte => ">=",
        ecel::Comparator::Lte => "<=",
        ecel::Comparator::Gt => ">",
        ecel::Comparator::Lt => "<",
        ecel::Comparator::In => "in",
        ecel::Comparator::Matches => "matches",
    }
}

