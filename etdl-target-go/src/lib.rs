/// The Go analog of `etdl_core::retry::RetryPolicy` — the attempt-count
/// and backoff *sequence* are computed once, in Rust
/// (`etdl_retry_policy_execute`'s native loop), via a `runtime/cgo.Handle`
/// (the standard, documented mechanism for passing Go state through a C
/// callback since Go 1.17) bound to a Go closure through a small C shim
/// function — cgo cannot directly marshal a Go `//export`ed function into
/// an anonymous (non-`typedef`'d) C function-pointer parameter, so the
/// shim (`etdl_retry_policy_execute_shim`, pure C, calling the real
/// function with the exported Go trampoline as a plain named argument)
/// sidesteps that entirely. Per-attempt timeout enforcement stays here
/// (see `docs/architecture/targets.md`'s "Ownership model": no FFI
/// boundary can safely cancel foreign code mid-flight) using a goroutine +
/// channel + `time.After` — note the timed-out goroutine itself cannot be
/// forcibly killed either; only the *retry loop* moves on.
const RETRY_POLICY_GO: &str = r#"// Read-only ETDL runtime. DO NOT EDIT DIRECTLY.
package etdlruntime

/*
#include <stdint.h>
#include "etdl_runtime.h"

extern int32_t goEtdlRetryTrampoline(void* user_data, uint32_t attempt);

static int32_t etdl_retry_policy_execute_shim(const EtdlRetryPolicy* handle, void* user_data, uint32_t* out_attempts_used) {
    return etdl_retry_policy_execute(handle, goEtdlRetryTrampoline, user_data, out_attempts_used);
}
*/
import "C"

import (
	"errors"
	"fmt"
	"runtime/cgo"
	"time"
	"unsafe"
)

type BackoffStrategy int32

const (
	BackoffFixed       BackoffStrategy = 0
	BackoffExponential BackoffStrategy = 1
)

type RetryPolicy struct {
	handle *C.EtdlRetryPolicy
}

func NewRetryPolicy(maxAttempts uint32, backoffMs uint64, strategy BackoffStrategy) (*RetryPolicy, error) {
	h := C.etdl_retry_policy_new(C.uint32_t(maxAttempts), C.uint64_t(backoffMs), C.int32_t(strategy))
	if h == nil {
		return nil, fmt.Errorf("etdl_retry_policy_new failed: %s", LastError())
	}
	return &RetryPolicy{handle: h}, nil
}

func (r *RetryPolicy) Close() {
	if r.handle != nil {
		C.etdl_retry_policy_free(r.handle)
		r.handle = nil
	}
}

// retryCallback is what a Go attempt reports back to the native retry
// loop: 0 success, positive retryable, negative fatal — exactly
// etdl_retry_policy_execute's documented callback contract.
type retryCallback func(attempt uint32) int32

//export goEtdlRetryTrampoline
func goEtdlRetryTrampoline(userData unsafe.Pointer, attempt C.uint32_t) C.int32_t {
	h := cgo.Handle(uintptr(userData))
	cb := h.Value().(retryCallback)
	return C.int32_t(cb(uint32(attempt)))
}

type attemptResult struct {
	value any
	err   error
}

// Execute runs op, retrying per this policy's configured attempts/backoff
// (computed once, authoritatively, in Rust). A *WorkflowError op returns
// is retryable; any other error is fatal (not retried) — mirroring every
// other target's binding. op's own panic is caught here and converted to
// a fatal error — it never crosses the native call.
func (r *RetryPolicy) Execute(op func() (any, error), timeout time.Duration) (any, error) {
	var result any
	var checkedErr error
	var fatalErr error

	cb := retryCallback(func(attempt uint32) int32 {
		ch := make(chan attemptResult, 1)
		go func() {
			defer func() {
				if p := recover(); p != nil {
					ch <- attemptResult{nil, fmt.Errorf("panic in operation: %v", p)}
				}
			}()
			v, err := op()
			ch <- attemptResult{v, err}
		}()

		var res attemptResult
		if timeout > 0 {
			select {
			case res = <-ch:
			case <-time.After(timeout):
				checkedErr = fmt.Errorf("operation timed out after %s", timeout)
				return 1
			}
		} else {
			res = <-ch
		}

		if res.err == nil {
			result = res.value
			return 0
		}
		var we *WorkflowError
		if errors.As(res.err, &we) {
			checkedErr = res.err
			return 1
		}
		fatalErr = res.err
		return -1
	})

	handle := cgo.NewHandle(cb)
	defer handle.Delete()

	var attemptsUsed C.uint32_t
	rc := C.etdl_retry_policy_execute_shim(r.handle, unsafe.Pointer(uintptr(handle)), &attemptsUsed)

	switch int32(rc) {
	case RetryOk:
		return result, nil
	case RetryFatal:
		if fatalErr != nil {
			return nil, fatalErr
		}
		return nil, fmt.Errorf("retry failed fatally: %s", LastError())
	default: // RetryExhausted
		if checkedErr != nil {
			return nil, checkedErr
		}
		return nil, fmt.Errorf("retry exhausted: %s", LastError())
	}
}
"#;

/// The Go analog of `etdl_core::condition::{contains, matches}` — ECEL
/// `in`/`matches` semantics stay in Rust; this facade only marshals
/// values to/from the JSON text `etdl_condition_contains` expects, using
/// `encoding/json` (Go's standard library — no extra module dependency).
const CONDITION_GO: &str = r#"// Read-only ETDL runtime. DO NOT EDIT DIRECTLY.
//
// ECEL (core spec Section 6) `in`/`matches` operators lower to these
// helpers, delegating to the native etdl_core::condition module (via
// etdl-runtime-ffi) — so a `matches` regex or an `in` membership check
// behaves byte-for-byte identically no matter which target (Rust, Java,
// Python, Go, .NET) evaluates it.
package etdlruntime

/*
#include "etdl_runtime.h"
*/
import "C"

import (
	"encoding/json"
	"fmt"
)

func Matches(value, pattern string) (bool, error) {
	cValue := cstr(value)
	defer freeCstr(cValue)
	cPattern := cstr(pattern)
	defer freeCstr(cPattern)
	rc := C.etdl_condition_matches(cValue, cPattern)
	if rc < 0 {
		return false, fmt.Errorf("etdl_condition_matches: %s", LastError())
	}
	return rc == 1, nil
}

func Contains(haystack any, needle any) (bool, error) {
	needleJSON, err := json.Marshal(needle)
	if err != nil {
		return false, fmt.Errorf("marshal needle: %w", err)
	}
	haystackJSON, err := json.Marshal(haystack)
	if err != nil {
		return false, fmt.Errorf("marshal haystack: %w", err)
	}
	cNeedle := cstr(string(needleJSON))
	defer freeCstr(cNeedle)
	cHaystack := cstr(string(haystackJSON))
	defer freeCstr(cHaystack)
	rc := C.etdl_condition_contains(cNeedle, cHaystack)
	if rc < 0 {
		return false, fmt.Errorf("etdl_condition_contains: %s", LastError())
	}
	return rc == 1, nil
}
"#;

