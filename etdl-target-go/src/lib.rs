//! The `go` [`CodeGenerator`] target.
//!
//! Consumes the exact same validated [`EtlDocument`] + resolved fault-tree
//! probabilities + [`AsyncApiRegistry`] every other target consumes.
//! Nothing here re-parses `.etdl`, re-validates ECEL conditions, or
//! re-evaluates fault trees. Generated Go is a thin `cgo` binding to the
//! same compiled `etdl-runtime-ffi` C ABI the Java/Python/.NET targets
//! bind to — not a reimplementation of ETDL semantics. See
//! `docs/architecture/targets.md`.
//!
//! Building this crate never requires a Go toolchain — it only emits Go
//! source text (plus a minimal `go.mod`). A Go toolchain (with `cgo`
//! enabled, the default) is needed only to *build and run* the generated
//! output, and `etdl-runtime-ffi`'s compiled shared/static library plus
//! its `include/etdl_runtime.h` header are needed to build anything that
//! touches `BranchMonitor`/`RetryPolicy`/`Condition`.
//!
//! # Untested in this environment
//!
//! Unlike the Java/Python/.NET targets (each verified end-to-end against
//! the real compiled `etdl-runtime-ffi` library in this repository's own
//! test suite), **no Go toolchain was available in the environment this
//! target was implemented in**, so none of its generated `cgo` code has
//! been compiled or run. It follows well-established, documented `cgo`
//! idioms throughout (`runtime/cgo.Handle` for passing Go state through a
//! C callback — the standard mechanism since Go 1.17; a small C shim
//! function per callback site, so cgo never has to marshal an anonymous
//! C function-pointer type; `C._Bool`, not `C.bool`, for C99 `_Bool`
//! parameters) and was reasoned through carefully, but it should be
//! verified against a real `go build` before being relied on — see
//! `etdl-target-go/tests/go_generation.rs`'s `go_build_*` tests, which
//! skip with a clear message when `go` isn't on `PATH` rather than
//! silently passing.

use etdl_compiler::{CodeGenerator, Diagnostic, GeneratedFile};
use etdl_parser::ast::{
    BackoffStrategy as AstBackoffStrategy, ChannelRef, Condition, EtlDocument, EventTree,
    MessageRef, Node,
};
use etdl_parser::asyncapi::AsyncApiRegistry;
use etdl_parser::ecel;
use std::collections::BTreeMap;

const GO_MODULE: &str = "etdlgenerated";

pub struct GoCodeGenerator {
    pub version: String,
    /// Go package name for document-specific output. `None` derives it
    /// (lowercased, no separators — Go package-naming convention) from
    /// `info.domain`.
    pub package: Option<String>,
}

impl Default for GoCodeGenerator {
    fn default() -> Self {
        Self::new()
    }
}

impl GoCodeGenerator {
    pub fn new() -> Self {
        GoCodeGenerator {
            version: env!("CARGO_PKG_VERSION").to_string(),
            package: None,
        }
    }

    fn resolve_package(&self, doc: &EtlDocument) -> String {
        if let Some(ref p) = self.package {
            return p.clone();
        }
        sanitize_package(&doc.info.domain)
    }
}

impl CodeGenerator for GoCodeGenerator {
    fn target_name(&self) -> &'static str {
        "go"
    }

    fn generate_all(
        &self,
        doc: &EtlDocument,
        fault_tree_probs: &BTreeMap<String, f64>,
        registry: &AsyncApiRegistry,
        stem: &str,
        _diagnostics: &mut Vec<Diagnostic>,
    ) -> Result<Vec<GeneratedFile>, String> {
        let package = self.resolve_package(doc);
        let _ = stem;

        let mut files = runtime_files();
        files.push(GeneratedFile::new("go.mod", generate_go_mod()));

        let message_refs = collect_message_refs(doc);
        if !message_refs.is_empty() {
            let mut messages_file = String::new();
            messages_file.push_str("// AUTOGENERATED BY ETDL COMPILER - DO NOT EDIT DIRECTLY\n\n");
            messages_file.push_str(&format!("package {package}\n\n"));
            for (type_name, msg_ref) in &message_refs {
                let value = registry
                    .resolve_message(doc, msg_ref)
                    .map_err(|e| format!("resolving message for '{type_name}': {e}"))?;
                messages_file.push_str(&generate_message_struct(type_name, &value));
            }
            files.push(GeneratedFile::new(
                format!("{package}/messages.go"),
                messages_file,
            ));
        }

        for tree in doc.event_trees.values() {
            let tree_id = tree_id_of(doc, tree);
            let iface_name = format!("{}Handlers", to_pascal_case(&sanitize_ident(tree_id)));
            let handler_methods = collect_handler_methods(tree);
            let msg_type = ref_to_type_name(&tree.initiating_event.message);
            let module_name = to_snake_case(&sanitize_ident(tree_id));
            files.push(GeneratedFile::new(
                format!("{package}/{module_name}_handlers.go"),
                generate_handlers_interface(&package, &iface_name, &msg_type, &handler_methods),
            ));
        }

        let workflow = generate_workflow_file(doc, &package, fault_tree_probs)?;
        files.push(GeneratedFile::new(
            format!("{package}/workflow.go"),
            workflow,
        ));

        Ok(files)
    }
}

fn tree_id_of<'a>(doc: &'a EtlDocument, tree: &EventTree) -> &'a str {
    doc.event_trees
        .iter()
        .find(|(_, t)| std::ptr::eq(*t, tree))
        .map(|(id, _)| id.as_str())
        .unwrap_or("Tree")
}

fn generate_go_mod() -> String {
    format!(
        r#"// AUTOGENERATED BY ETDL COMPILER - safe to edit (rename the module, add your own
// developer .go files/packages anywhere in this tree, add `require`
// directives for your own dependencies).
module {GO_MODULE}

go 1.21
"#
    )
}

