fn collect_message_refs(doc: &EtlDocument) -> BTreeMap<String, MessageRef> {
    let mut refs: BTreeMap<String, MessageRef> = BTreeMap::new();
    let note = |m: &MessageRef, refs: &mut BTreeMap<String, MessageRef>| {
        let name = ref_to_type_name(m);
        refs.entry(name).or_insert_with(|| m.clone());
    };

    for tree in doc.event_trees.values() {
        note(&tree.initiating_event.message, &mut refs);
        for node in tree.nodes.values() {
            match node {
                Node::Operation(op) => {
                    if let Some(ref m) = op.emits {
                        note(m, &mut refs);
                    }
                }
                Node::Consequence(cons) => {
                    if let Some(ref m) = cons.message {
                        note(m, &mut refs);
                    }
                }
                _ => {}
            }
        }
    }

    if let Some(ref fault_trees) = doc.fault_trees {
        for ft in fault_trees.values() {
            if let Some(ref m) = ft.top_event.message {
                note(m, &mut refs);
            }
            for be in ft.basic_events.values() {
                if let Some(ref m) = be.message {
                    note(m, &mut refs);
                }
            }
        }
    }

    refs
}

fn ref_to_type_name(msg_ref: &MessageRef) -> String {
    let pointer = match msg_ref {
        MessageRef::External(r) => &r.pointer,
        MessageRef::Internal(r) => &r.pointer,
    };
    extract_last_segment(pointer)
}

fn extract_last_segment(pointer: &str) -> String {
    let last = pointer.rsplit('/').next().unwrap_or("Unknown");
    to_pascal_case(last)
}

fn generate_message_struct(type_name: &str, message: &serde_json::Value) -> String {
    let payload_type_name = format!("{type_name}Payload");
    let payload_schema = message.get("payload").cloned().unwrap_or(serde_json::Value::Null);

    let mut nested = String::new();
    let payload_go_type = schema_to_go_type(&payload_type_name, &payload_schema, &mut nested);

    let mut out = String::new();
    out.push_str(&nested);
    out.push_str(&format!("type {type_name} struct {{\n"));
    out.push_str(&format!("\tPayload {payload_go_type} `json:\"payload\"`\n"));
    out.push_str("\tHeaders map[string]any `json:\"headers,omitempty\"`\n");
    out.push_str("}\n\n");
    out
}

/// Go analog of the other targets' struct/record/dataclass generators. Go
/// struct fields have no ordering constraint (unlike Python's
/// `@dataclass`/C#'s positional `record`), so — unlike those two targets —
/// schema property order is kept as-is; only the "optional field becomes a
/// pointer type" convention (Go's idiomatic nullable) differs per target.
fn generate_struct_from_schema(name: &str, schema: &serde_json::Value, output: &mut String) {
    let Some(properties) = schema.get("properties").and_then(|p| p.as_object()) else {
        return;
    };

    let required: std::collections::BTreeSet<&str> = schema
        .get("required")
        .and_then(|r| r.as_array())
        .map(|arr| arr.iter().filter_map(|v| v.as_str()).collect())
        .unwrap_or_default();

    let mut nested = String::new();
    let mut fields = String::new();

    for (field_name, field_schema) in properties {
        let pascal = to_pascal_case(field_name);
        let nested_type_name = format!("{name}{pascal}");
        let is_required = required.contains(field_name.as_str());
        let go_type = schema_to_go_type(&nested_type_name, field_schema, &mut nested);
        // Deliberately never pointer-wraps an optional field (unlike the
        // Python/C#/Java targets' nullable equivalents): ECEL condition
        // codegen (`build_path_expression`/`append_segment`) generates
        // plain field-access expressions with no schema/type awareness of
        // which fields are optional, so a condition comparing or
        // `range`-ing over an optional field must see a directly usable
        // value — a `*string`/`*[]T` would need an explicit nil-check/
        // deref at every access site codegen doesn't (and, without
        // threading schema types through condition codegen, safely can't)
        // insert. The tradeoff: a Go struct can't distinguish "field
        // absent" from "field present with its zero value" the way the
        // other targets' nullable types can — documented in
        // docs/architecture/targets.md's Go section.
        let omit = if is_required { "" } else { ",omitempty" };
        fields.push_str(&format!(
            "\t{pascal} {go_type} `json:\"{field_name}{omit}\"`\n"
        ));
    }

    output.push_str(&nested);
    output.push_str(&format!("type {name} struct {{\n{fields}}}\n\n"));
}

fn schema_to_go_type(candidate_name: &str, schema: &serde_json::Value, nested: &mut String) -> String {
    match schema.get("type").and_then(|t| t.as_str()) {
        Some("string") => "string".to_string(),
        Some("integer") => "int64".to_string(),
        Some("number") => "float64".to_string(),
        Some("boolean") => "bool".to_string(),
        Some("array") => {
            let item_type = match schema.get("items") {
                Some(items_schema) => {
                    schema_to_go_type(&format!("{candidate_name}Item"), items_schema, nested)
                }
                None => "any".to_string(),
            };
            format!("[]{item_type}")
        }
        Some("object") => {
            if schema.get("properties").is_some() {
                generate_struct_from_schema(candidate_name, schema, nested);
                candidate_name.to_string()
            } else {
                "map[string]any".to_string()
            }
        }
        _ => "any".to_string(),
    }
}

