//! The `python` [`CodeGenerator`] target.
//!
//! Consumes the exact same validated [`EtlDocument`] + resolved fault-tree
//! probabilities + [`AsyncApiRegistry`] every other target consumes.
//! Nothing here re-parses `.etdl`, re-validates ECEL conditions, or
//! re-evaluates fault trees. Generated Python is a thin, `ctypes`-based
//! binding to the same compiled `etdl-runtime-ffi` C ABI the Java target
//! binds to via `java.lang.foreign` — branch/SLA accounting, retry
//! backoff, and ECEL `matches`/`in` semantics stay in Rust. See
//! `docs/architecture/targets.md`.
//!
//! Building this crate never requires Python — it only emits Python
//! source text. Python (3.9+, for the `list[T]`/`X | None` type-hint
//! syntax generated code uses) is needed only to *run* the generated
//! output, and `etdl-runtime-ffi`'s compiled shared library is needed to
//! run anything that touches `BranchMonitor`/`RetryPolicy`/`Condition`.
//! `ctypes` is Python's standard library — no `pip install` is needed
//! either.

use etdl_compiler::{CodeGenerator, Diagnostic, GeneratedFile};
use etdl_parser::ast::{
    BackoffStrategy as AstBackoffStrategy, ChannelRef, Condition, EtlDocument, EventTree,
    MessageRef, Node,
};
use etdl_parser::asyncapi::AsyncApiRegistry;
use etdl_parser::ecel;
use std::collections::BTreeMap;

pub struct PythonCodeGenerator {
    pub version: String,
    /// Python package for document-specific output. `None` derives it
    /// (snake_case) from `info.domain`.
    pub package: Option<String>,
}

impl Default for PythonCodeGenerator {
    fn default() -> Self {
        Self::new()
    }
}

impl PythonCodeGenerator {
    pub fn new() -> Self {
        PythonCodeGenerator {
            version: env!("CARGO_PKG_VERSION").to_string(),
            package: None,
        }
    }

    fn resolve_package(&self, doc: &EtlDocument) -> String {
        if let Some(ref p) = self.package {
            return p.clone();
        }
        sanitize_package(&doc.info.domain)
    }
}

impl CodeGenerator for PythonCodeGenerator {
    fn target_name(&self) -> &'static str {
        "python"
    }

    fn generate_all(
        &self,
        doc: &EtlDocument,
        fault_tree_probs: &BTreeMap<String, f64>,
        registry: &AsyncApiRegistry,
        stem: &str,
        _diagnostics: &mut Vec<Diagnostic>,
    ) -> Result<Vec<GeneratedFile>, String> {
        let package = self.resolve_package(doc);
        let _ = stem;

        let mut files = runtime_files();
        files.push(GeneratedFile::new(format!("{package}/__init__.py"), String::new()));

        let message_refs = collect_message_refs(doc);
        let mut messages_module = String::new();
        messages_module.push_str("\"\"\"AUTOGENERATED BY ETDL COMPILER - DO NOT EDIT DIRECTLY.\n\n");
        messages_module.push_str("Message dataclasses resolved from AsyncAPI schemas (both External and\n");
        messages_module.push_str("Internal References, via `AsyncApiRegistry.resolve_message` upstream in\n");
        messages_module.push_str("the compiler) referenced anywhere in this document.\n\"\"\"\n\n");
        messages_module.push_str("from __future__ import annotations\n\n");
        messages_module.push_str("from dataclasses import dataclass\n\n");
        for (type_name, msg_ref) in &message_refs {
            let value = registry
                .resolve_message(doc, msg_ref)
                .map_err(|e| format!("resolving message for '{type_name}': {e}"))?;
            messages_module.push_str(&generate_message_dataclass(type_name, &value));
        }
        if !message_refs.is_empty() {
            files.push(GeneratedFile::new(
                format!("{package}/messages.py"),
                messages_module,
            ));
        }

        for tree in doc.event_trees.values() {
            let tree_id = tree_id_of(doc, tree);
            let module_name = to_snake_case(&sanitize_ident(tree_id));
            let class_name = format!("{}Handlers", to_pascal_case(&sanitize_ident(tree_id)));
            let handler_methods = collect_handler_methods(tree);
            files.push(GeneratedFile::new(
                format!("{package}/{module_name}_handlers.py"),
                generate_handlers_module(&class_name, &handler_methods, !message_refs.is_empty()),
            ));
        }

        let workflow = generate_workflow_module(doc, fault_tree_probs, !message_refs.is_empty())?;
        files.push(GeneratedFile::new(format!("{package}/workflow.py"), workflow));

        Ok(files)
    }
}

fn tree_id_of<'a>(doc: &'a EtlDocument, tree: &EventTree) -> &'a str {
    doc.event_trees
        .iter()
        .find(|(_, t)| std::ptr::eq(*t, tree))
        .map(|(id, _)| id.as_str())
        .unwrap_or("Tree")
}

