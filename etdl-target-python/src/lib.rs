fn generate_workflow_module(
    doc: &EtlDocument,
    fault_tree_probs: &BTreeMap<String, f64>,
    has_messages: bool,
) -> Result<String, String> {
    let mut out = String::new();
    out.push_str("\"\"\"AUTOGENERATED BY ETDL COMPILER - DO NOT EDIT DIRECTLY.\"\"\"\n\n");
    out.push_str("from __future__ import annotations\n\n");
    out.push_str("from etdl.runtime.branch_monitor import BranchMonitor\n");
    out.push_str("from etdl.runtime.condition import contains, matches\n");
    out.push_str("from etdl.runtime.errors import WorkflowError\n");
    out.push_str("from etdl.runtime.publisher import Publisher\n");
    out.push_str("from etdl.runtime.retry_policy import BackoffStrategy, RetryPolicy\n");
    if has_messages {
        out.push_str("\nfrom .messages import *  # noqa: F401,F403\n");
    }
    for tree in doc.event_trees.values() {
        let tree_id = tree_id_of(doc, tree);
        let module_name = to_snake_case(&sanitize_ident(tree_id));
        let class_name = format!("{}Handlers", to_pascal_case(&sanitize_ident(tree_id)));
        out.push_str(&format!("from .{module_name}_handlers import {class_name}\n"));
    }
    out.push('\n');

    out.push_str(&generate_fault_tree_constants(doc, fault_tree_probs));

    for tree in doc.event_trees.values() {
        let method = generate_event_tree_function(doc, tree, fault_tree_probs)?;
        out.push_str(&method);
        out.push('\n');
    }

    Ok(out)
}

fn generate_fault_tree_constants(doc: &EtlDocument, fault_tree_probs: &BTreeMap<String, f64>) -> String {
    let mut output = String::new();
    for tree in doc.event_trees.values() {
        for (node_id, node) in &tree.nodes {
            if let Node::Operation(op) = node {
                if let Some(ref ps) = op.on_failure_probability_source {
                    if let Some((ft_id, prob)) = find_fault_tree_prob(ps, fault_tree_probs) {
                        output.push_str(&format!(
                            "# Computed from faultTrees.{ft_id}.topEvent at build time (Section 5.16)\n"
                        ));
                        let const_name = to_upper_snake(&format!("{node_id}_failure_probability"));
                        output.push_str(&format!("{const_name}: float = {prob:.6}\n\n"));
                    }
                }
            }
        }
    }
    output
}

fn find_fault_tree_prob(
    ps: &etdl_parser::ast::InternalRef,
    fault_tree_probs: &BTreeMap<String, f64>,
) -> Option<(String, f64)> {
    let ft_id = extract_ft_id(&ps.pointer);
    fault_tree_probs.get(&ft_id).map(|&v| (ft_id.clone(), v))
}

fn extract_ft_id(pointer: &str) -> String {
    pointer
        .trim_start_matches("#/faultTrees/")
        .trim_end_matches("/topEvent")
        .to_string()
}

fn generate_event_tree_function(
    doc: &EtlDocument,
    tree: &EventTree,
    fault_tree_probs: &BTreeMap<String, f64>,
) -> Result<String, String> {
    let mut out = String::new();

    let tree_id = tree_id_of(doc, tree);
    let class_name = format!("{}Handlers", to_pascal_case(&sanitize_ident(tree_id)));
    let function_name = format!("handle_{}", to_snake_case(&sanitize_ident(&tree.initiating_event.id)));

    out.push_str(&format!(
        "def {function_name}(message, publisher: Publisher, handlers: {class_name}) -> None:\n"
    ));

    let first_barrier = find_first_barrier(tree);
    let monitor_name = first_barrier.map(to_snake_case).unwrap_or_else(|| "monitor".to_string());
    out.push_str(&format!(
        "    with BranchMonitor(\"{}\") as {monitor_name}:\n",
        first_barrier.unwrap_or("root")
    ));

    let start_node_id = &tree.initiating_event.next;
    let body = generate_node_code(doc, tree, start_node_id, 2, fault_tree_probs, &monitor_name)?;
    out.push_str(&body);

    Ok(out)
}

fn find_first_barrier(tree: &EventTree) -> Option<&str> {
    let mut current = &tree.initiating_event.next;
    loop {
        match tree.nodes.get(current.as_str()) {
            Some(Node::Barrier(_)) => return Some(current.as_str()),
            Some(Node::Operation(op)) => current = &op.next,
            Some(Node::Consequence(_)) => return None,
            None => return None,
        }
    }
}

fn generate_node_code(
    doc: &EtlDocument,
    tree: &EventTree,
    node_id: &str,
    depth: usize,
    fault_tree_probs: &BTreeMap<String, f64>,
    monitor_name: &str,
) -> Result<String, String> {
    let node = tree
        .nodes
        .get(node_id)
        .ok_or_else(|| format!("node '{node_id}' not found"))?;

    match node {
        Node::Barrier(barrier) => {
            generate_barrier_code(tree, node_id, barrier, depth, doc, fault_tree_probs, monitor_name)
        }
        Node::Operation(op) => {
            generate_operation_code(tree, node_id, op, depth, doc, fault_tree_probs, monitor_name)
        }
        Node::Consequence(cons) => generate_consequence_code(cons, depth),
    }
}

fn generate_barrier_code(
    tree: &EventTree,
    node_id: &str,
    barrier: &etdl_parser::ast::Barrier,
    depth: usize,
    doc: &EtlDocument,
    fault_tree_probs: &BTreeMap<String, f64>,
    monitor_name: &str,
) -> Result<String, String> {
    let indent = "    ".repeat(depth);
    let mut output = String::new();

    for (i, branch) in barrier.branches.iter().enumerate() {
        let is_default = branch.condition == Condition::Default;
        let keyword = if i == 0 {
            "if"
        } else if is_default {
            "else"
        } else {
            "elif"
        };

        if is_default && i > 0 {
            output.push_str(&format!("{indent}else:\n"));
        } else {
            let cond = condition_to_python_code(&branch.condition);
            output.push_str(&format!("{indent}{keyword} {cond}:\n"));
        }

        emit_branch_record(&format!("{indent}    "), monitor_name, branch, node_id, fault_tree_probs, &mut output);
        let body = generate_node_code(doc, tree, &branch.next, depth + 1, fault_tree_probs, monitor_name)?;
        output.push_str(&body);
    }

    Ok(output)
}

fn emit_branch_record(
    indent: &str,
    monitor_name: &str,
    branch: &etdl_parser::ast::Branch,
    node_id: &str,
    fault_tree_probs: &BTreeMap<String, f64>,
    output: &mut String,
) {
    if let Some(p) = get_branch_prob(branch, node_id, fault_tree_probs) {
        output.push_str(&format!(
            "{indent}{monitor_name}.record_branch(\"{}\", {p:.6})\n",
            branch.outcome
        ));
    } else {
        output.push_str(&format!("{indent}pass\n"));
    }
}

fn get_branch_prob(
    branch: &etdl_parser::ast::Branch,
    _node_id: &str,
    fault_tree_probs: &BTreeMap<String, f64>,
) -> Option<f64> {
    if let Some(ref ps) = branch.probability_source {
        let ft_id = extract_ft_id(&ps.pointer);
        return fault_tree_probs.get(&ft_id).copied();
    }
    branch.effective_probability()
}

fn generate_operation_code(
    tree: &EventTree,
    node_id: &str,
    op: &etdl_parser::ast::Operation,
    depth: usize,
    doc: &EtlDocument,
    fault_tree_probs: &BTreeMap<String, f64>,
    monitor_name: &str,
) -> Result<String, String> {
    let indent = "    ".repeat(depth);
    let mut output = String::new();

    let handler_name = to_snake_case(&op.handler);
    let timeout_s = op.timeout_ms.unwrap_or(5000) as f64 / 1000.0;

    output.push_str(&format!("{indent}try:\n"));
    if let Some(ref retry) = op.retry_policy {
        let strategy = match retry.backoff_strategy.as_ref().unwrap_or(&AstBackoffStrategy::Fixed) {
            AstBackoffStrategy::Exponential => "BackoffStrategy.EXPONENTIAL",
            AstBackoffStrategy::Fixed => "BackoffStrategy.FIXED",
        };
        output.push_str(&format!(
            "{indent}    with RetryPolicy({}, {}, {strategy}) as retry:\n",
            retry.max_attempts, retry.backoff_ms
        ));
        output.push_str(&format!(
            "{indent}        _result = retry.execute(lambda: handlers.{handler_name}(message), timeout_s={timeout_s})\n"
        ));
    } else {
        output.push_str(&format!(
            "{indent}    _result = handlers.{handler_name}(message)\n"
        ));
    }

    if op.on_failure.is_some() {
        if let Some(ref ps) = op.on_failure_probability_source {
            let const_name = to_upper_snake(&format!("{node_id}_failure_probability"));
            let prob_exists = find_fault_tree_prob(ps, fault_tree_probs).is_some();
            let indent2 = "    ".repeat(depth + 1 + usize::from(op.retry_policy.is_some()));
            if prob_exists {
                output.push_str(&format!(
                    "{indent2}{monitor_name}.record_success(\"{node_id}\", {const_name})\n"
                ));
            } else {
                output.push_str(&format!(
                    "{indent2}{monitor_name}.record_success(\"{node_id}\", None)\n"
                ));
            }
        }
    }

    let body_indent = depth + 1 + usize::from(op.retry_policy.is_some());
    let next_node = tree.nodes.get(&op.next);
    match next_node {
        Some(Node::Consequence(cons)) => {
            emit_send(cons, "_result", &"    ".repeat(body_indent), &mut output);
        }
        Some(_) => {
            let body = generate_node_code(doc, tree, &op.next, body_indent, fault_tree_probs, monitor_name)?;
            output.push_str(&body);
        }
        None => {
            output.push_str(&format!("{}pass\n", "    ".repeat(body_indent)));
        }
    }

    output.push_str(&format!("{indent}except WorkflowError as err:\n"));

    if let Some(ref ps) = op.on_failure_probability_source {
        let const_name = to_upper_snake(&format!("{node_id}_failure_probability"));
        let prob_exists = find_fault_tree_prob(ps, fault_tree_probs).is_some();
        if prob_exists {
            output.push_str(&format!(
                "{indent}    {monitor_name}.record_failure(\"{node_id}\", err, {const_name})\n"
            ));
        } else {
            output.push_str(&format!(
                "{indent}    {monitor_name}.record_failure(\"{node_id}\", err, None)\n"
            ));
        }
    } else {
        output.push_str(&format!(
            "{indent}    {monitor_name}.record_failure(\"{node_id}\", err, None)\n"
        ));
    }

    if let Some(ref on_failure_id) = op.on_failure {
        match tree.nodes.get(on_failure_id) {
            Some(Node::Consequence(cons)) => {
                emit_send(cons, "message", &format!("{indent}    "), &mut output);
            }
            _ => {
                let body = generate_node_code(doc, tree, on_failure_id, depth + 1, fault_tree_probs, monitor_name)?;
                output.push_str(&body);
            }
        }
    } else {
        output.push_str(&format!("{indent}    raise\n"));
    }

    Ok(output)
}

fn emit_send(cons: &etdl_parser::ast::Consequence, payload_expr: &str, indent: &str, output: &mut String) {
    if let etdl_parser::ast::ConsequenceOperation::Send = cons.consequence_operation {
        if let Some(ref channel_ref) = cons.channel {
            let channel_name = channel_ref_name(channel_ref);
            output.push_str(&format!(
                "{indent}publisher.publish(\"{channel_name}\", {payload_expr})\n"
            ));
            return;
        }
    }
    output.push_str(&format!("{indent}pass\n"));
}

fn generate_consequence_code(cons: &etdl_parser::ast::Consequence, depth: usize) -> Result<String, String> {
    let indent = "    ".repeat(depth);
    let mut output = String::new();

    if let etdl_parser::ast::ConsequenceOperation::Send = cons.consequence_operation {
        if let Some(ref channel_ref) = cons.channel {
            let channel_name = channel_ref_name(channel_ref);
            output.push_str(&format!("{indent}publisher.publish(\"{channel_name}\", message)\n"));
            return Ok(output);
        }
    }
    output.push_str(&format!("{indent}pass\n"));
    Ok(output)
}

fn channel_ref_name(channel_ref: &ChannelRef) -> String {
    match channel_ref {
        ChannelRef::External(ext_ref) => extract_last_segment(&ext_ref.pointer),
        ChannelRef::Bare(name) => name.clone(),
    }
}

// ---------------------------------------------------------------------
// ECEL condition -> Python
// ---------------------------------------------------------------------

fn condition_to_python_code(condition: &Condition) -> String {
    match condition {
        Condition::Default => "True".to_string(),
        Condition::Comparison(cmp) => {
            use ecel::Comparator as C;
            match cmp.op {
                C::In => {
                    let left = path_or_literal(&cmp.left);
                    let right = array_or_literal(&cmp.right);
                    format!("contains({right}, {left})")
                }
                C::Matches => {
                    let left = operand_to_path_expr_or_literal(&cmp.left);
                    let right = literal_to_val_str(&literal_of(&cmp.right));
                    format!("matches({left}, {right})")
                }
                _ => {
                    let (left_path, has_wildcard) = build_path_expression(&cmp.left);
                    let right = operand_to_val_str(&cmp.right);
                    let op = comparator_str(&cmp.op);

                    if has_wildcard {
                        format!(
                            "all(item{} {} {} for item in {})",
                            left_path.remaining_path, op, right, left_path.path_prefix
                        )
                    } else {
                        let l = if left_path.path_prefix.is_empty() && left_path.remaining_path.is_empty() {
                            operand_to_val_str(&cmp.left)
                        } else {
                            left_path.path_prefix + &left_path.remaining_path
                        };
                        let r = if right.is_empty() { operand_to_path_expr(&cmp.right) } else { right };
                        format!("{l} {op} {r}")
                    }
                }
            }
        }
    }
}

fn path_or_literal(operand: &ecel::Operand) -> String {
    match operand {
        ecel::Operand::Path(_) => operand_to_path_expr(operand),
        ecel::Operand::Literal(lit) => literal_to_val_str(lit),
    }
}

fn array_or_literal(operand: &ecel::Operand) -> String {
    match operand {
        ecel::Operand::Path(_) => operand_to_path_expr(operand),
        ecel::Operand::Literal(lit) => literal_to_val_str(lit),
    }
}

fn operand_to_path_expr_or_literal(operand: &ecel::Operand) -> String {
    match operand {
        ecel::Operand::Path(_) => operand_to_path_expr(operand),
        ecel::Operand::Literal(lit) => literal_to_val_str(lit),
    }
}

fn literal_of(operand: &ecel::Operand) -> ecel::Literal {
    match operand {
        ecel::Operand::Literal(lit) => lit.clone(),
        ecel::Operand::Path(_) => ecel::Literal::String(String::new()),
    }
}

struct PathParts {
    path_prefix: String,
    remaining_path: String,
}

/// Python analog of the Rust/Java targets' path-expression builder.
/// Segments render as plain attribute access (`.field`) — unlike Java's
/// records, a Python `@dataclass`'s fields are ordinary attributes, not
/// accessor methods — and `Index`/`QuotedKey` segments render as `[...]`
/// subscripting, which works directly on both `list` (index) and `dict`
/// (key) without the method-call detour Java's `List`/`Map` fallback
/// types needed.
fn build_path_expression(operand: &ecel::Operand) -> (PathParts, bool) {
    match operand {
        ecel::Operand::Path(path_expr) => {
            let segments = &path_expr.segments;
            let mut pre_wildcard = Vec::new();
            let mut post_wildcard = Vec::new();
            let mut has_wildcard = false;

            for (i, seg) in segments.iter().enumerate() {
                if i == 0 {
                    continue;
                }
                if has_wildcard {
                    post_wildcard.push(seg.clone());
                } else if matches!(seg, ecel::PathSegment::Wildcard) {
                    has_wildcard = true;
                } else {
                    pre_wildcard.push(seg.clone());
                }
            }

            let mut prefix = String::from("message");
            for seg in &pre_wildcard {
                append_segment(&mut prefix, seg);
            }

            let mut suffix = String::new();
            for seg in &post_wildcard {
                append_segment(&mut suffix, seg);
            }

            (
                PathParts { path_prefix: prefix, remaining_path: suffix },
                has_wildcard,
            )
        }
        ecel::Operand::Literal(_) => (
            PathParts { path_prefix: String::new(), remaining_path: String::new() },
            false,
        ),
    }
}

fn append_segment(out: &mut String, seg: &ecel::PathSegment) {
    match seg {
        ecel::PathSegment::Field(name) => {
            out.push('.');
            out.push_str(&to_snake_case(name));
        }
        ecel::PathSegment::Index(idx) => {
            out.push_str(&format!("[{idx}]"));
        }
        ecel::PathSegment::QuotedKey(name) => {
            out.push_str(&format!("[\"{name}\"]"));
        }
        _ => {}
    }
}

fn operand_to_path_expr(operand: &ecel::Operand) -> String {
    match operand {
        ecel::Operand::Path(path) => {
            let mut out = String::from("message");
            for seg in path.segments.iter().skip(1) {
                if matches!(seg, ecel::PathSegment::Wildcard) {
                    continue;
                }
                append_segment(&mut out, seg);
            }
            out
        }
        ecel::Operand::Literal(_) => String::new(),
    }
}

fn operand_to_val_str(operand: &ecel::Operand) -> String {
    match operand {
        ecel::Operand::Path(_) => "".to_string(),
        ecel::Operand::Literal(lit) => literal_to_val_str(lit),
    }
}

fn literal_to_val_str(lit: &ecel::Literal) -> String {
    match lit {
        ecel::Literal::Number(n) => n.to_string(),
        ecel::Literal::String(s) => format!("\"{s}\""),
        ecel::Literal::Bool(b) => if *b { "True".to_string() } else { "False".to_string() },
        ecel::Literal::Null => "None".to_string(),
        ecel::Literal::Array(items) => {
            let inner: Vec<String> = items.iter().map(literal_to_val_str).collect();
            format!("[{}]", inner.join(", "))
        }
    }
}

fn comparator_str(op: &ecel::Comparator) -> &str {
    match op {
        ecel::Comparator::Eq => "==",
        ecel::Comparator::Neq => "!=",
        ecel::Comparator::Gte => ">=",
        ecel::Comparator::Lte => "<=",
        ecel::Comparator::Gt => ">",
        ecel::Comparator::Lt => "<",
        ecel::Comparator::In => "in",
        ecel::Comparator::Matches => "matches",
    }
}

