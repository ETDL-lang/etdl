/// The Python analog of `etdl_core::BranchMonitor` — not a
/// reimplementation: every method is a direct call into the same
/// `BranchMonitor` the Rust target's generated code has always used, via
/// `etdl-runtime-ffi`.
const BRANCH_MONITOR_PY: &str = r#""""Read-only ETDL runtime. DO NOT EDIT DIRECTLY.

Thin facade over the native `etdl_core::BranchMonitor` (via
`etdl-runtime-ffi`). Owns one native handle; always use as a context
manager (generated orchestration code always does) so
`etdl_branch_monitor_free` runs deterministically.
"""

from __future__ import annotations

from . import native


class BranchMonitor:
    def __init__(self, node_id: str) -> None:
        self._handle = native.lib.etdl_branch_monitor_new(node_id.encode("utf-8"))
        if not self._handle:
            raise RuntimeError(f"etdl_branch_monitor_new failed: {native.last_error()}")
        self._closed = False

    def record_branch(self, outcome: str, probability: float) -> None:
        rc = native.lib.etdl_branch_monitor_record_branch(
            self._handle, outcome.encode("utf-8"), probability
        )
        self._check(rc, "etdl_branch_monitor_record_branch")

    def record_success(self, operation_id: str, probability: float | None) -> None:
        rc = native.lib.etdl_branch_monitor_record_success(
            self._handle,
            operation_id.encode("utf-8"),
            probability if probability is not None else 0.0,
            probability is not None,
        )
        self._check(rc, "etdl_branch_monitor_record_success")

    def record_failure(
        self, operation_id: str, error: BaseException, probability: float | None
    ) -> None:
        rc = native.lib.etdl_branch_monitor_record_failure(
            self._handle,
            operation_id.encode("utf-8"),
            str(error).encode("utf-8"),
            probability if probability is not None else 0.0,
            probability is not None,
        )
        self._check(rc, "etdl_branch_monitor_record_failure")

    def _check(self, rc: int, call: str) -> None:
        if rc != native.OK:
            raise RuntimeError(f"{call} failed (code {rc}): {native.last_error()}")

    def close(self) -> None:
        if not self._closed:
            self._closed = True
            native.lib.etdl_branch_monitor_free(self._handle)

    def __enter__(self) -> "BranchMonitor":
        return self

    def __exit__(self, exc_type, exc, tb) -> None:
        self.close()
"#;

/// The Python analog of `etdl_core::retry::RetryPolicy` — the
/// attempt-count/backoff *sequence* is computed once, in Rust
/// (`etdl_retry_policy_execute`'s native loop), via a `ctypes.CFUNCTYPE`
/// callback bound to `op`. Per-attempt timeout enforcement stays here (see
/// `docs/architecture/targets.md`'s "Ownership model": no FFI boundary can
/// safely cancel foreign code mid-flight) using a one-shot thread pool —
/// note Python threads cannot be forcibly killed, so a "cancelled" timed
/// out call's thread still runs to completion in the background; only the
/// *retry loop* moves on.
const RETRY_POLICY_PY: &str = r#""""Read-only ETDL runtime. DO NOT EDIT DIRECTLY.

Thin facade over the native `etdl_core::RetryPolicy` (via
`etdl-runtime-ffi`'s callback-driven `etdl_retry_policy_execute`). Owns one
native handle; always use as a context manager.
"""

from __future__ import annotations

import ctypes
from concurrent.futures import ThreadPoolExecutor, TimeoutError as FutureTimeoutError
from typing import Any, Callable

from . import native
from .errors import WorkflowError


class BackoffStrategy:
    FIXED = 0
    EXPONENTIAL = 1


class RetryPolicy:
    def __init__(self, max_attempts: int, backoff_ms: int, strategy: int) -> None:
        self._handle = native.lib.etdl_retry_policy_new(max_attempts, backoff_ms, strategy)
        if not self._handle:
            raise RuntimeError(f"etdl_retry_policy_new failed: {native.last_error()}")
        self._closed = False

    def execute(self, op: Callable[[], Any], timeout_s: float | None = None) -> Any:
        """`op` is a zero-argument callable. May raise `WorkflowError`
        (retryable) or any other exception (fatal, not retried) — either
        way, the exception is captured here and never crosses the native
        call (ctypes callbacks cannot safely propagate a Python exception
        into C); it is re-raised by this method afterward instead."""
        result_box: dict[str, Any] = {}

        def trampoline(_user_data: int, _attempt: int) -> int:
            with ThreadPoolExecutor(max_workers=1) as executor:
                future = executor.submit(op)
                try:
                    result_box["value"] = future.result(timeout=timeout_s)
                    return 0
                except FutureTimeoutError:
                    result_box["checked_error"] = WorkflowError(
                        f"operation timed out after {timeout_s}s"
                    )
                    return 1
                except WorkflowError as e:
                    result_box["checked_error"] = e
                    return 1
                except BaseException as e:  # noqa: BLE001 - must never cross the FFI boundary
                    result_box["unchecked_error"] = e
                    return -1

        callback = native.RETRY_CALLBACK_TYPE(trampoline)
        attempts_used = ctypes.c_uint32(0)
        rc = native.lib.etdl_retry_policy_execute(
            self._handle, callback, None, ctypes.byref(attempts_used)
        )

        if rc == native.RETRY_OK:
            return result_box.get("value")
        if "unchecked_error" in result_box:
            raise result_box["unchecked_error"]
        if "checked_error" in result_box:
            raise result_box["checked_error"]
        kind = "retry failed fatally" if rc == native.RETRY_FATAL else "retry exhausted"
        raise WorkflowError(f"{kind}: {native.last_error()}")

    def close(self) -> None:
        if not self._closed:
            self._closed = True
            native.lib.etdl_retry_policy_free(self._handle)

    def __enter__(self) -> "RetryPolicy":
        return self

    def __exit__(self, exc_type, exc, tb) -> None:
        self.close()
"#;

/// The Python analog of `etdl_core::condition::{contains, matches}` — ECEL
/// `in`/`matches` semantics stay in Rust; this facade only marshals values
/// to/from the JSON text `etdl_condition_contains` expects, using Python's
/// standard-library `json` module (unlike the Java target, no
/// dependency-free hand-rolled encoder is needed here).
const CONDITION_PY: &str = r#""""Read-only ETDL runtime. DO NOT EDIT DIRECTLY.

ECEL (core spec Section 6) `in`/`matches` operators lower to these
helpers, delegating to the native `etdl_core::condition` module (via
`etdl-runtime-ffi`) — so a `matches` regex or an `in` membership check
behaves byte-for-byte identically no matter which target (Rust, Java,
Python, Go, .NET) evaluates it.
"""

from __future__ import annotations

import json
from typing import Any, Iterable

from . import native


def matches(value: str | None, pattern: str) -> bool:
    rc = native.lib.etdl_condition_matches(
        (value or "").encode("utf-8"), pattern.encode("utf-8")
    )
    if rc < 0:
        raise ValueError(f"etdl_condition_matches: {native.last_error()}")
    return rc == 1


def contains(haystack: Iterable[Any] | None, needle: Any) -> bool:
    needle_json = json.dumps(needle).encode("utf-8")
    haystack_json = json.dumps(list(haystack) if haystack is not None else []).encode("utf-8")
    rc = native.lib.etdl_condition_contains(needle_json, haystack_json)
    if rc < 0:
        raise ValueError(f"etdl_condition_contains: {native.last_error()}")
    return rc == 1
"#;

