    fn matches_operator_lowers_to_native_matches_call() {
        let cond = ecel::parse_condition(
            "message.payload.reference matches \"^ORD-[0-9]{8}$\"",
        )
        .unwrap();
        let code = condition_to_python_code(&cond);
        assert!(code.contains("matches("), "got: {code}");
    }

