fn collect_message_refs(doc: &EtlDocument) -> BTreeMap<String, MessageRef> {
    let mut refs: BTreeMap<String, MessageRef> = BTreeMap::new();
    let note = |m: &MessageRef, refs: &mut BTreeMap<String, MessageRef>| {
        let name = ref_to_type_name(m);
        refs.entry(name).or_insert_with(|| m.clone());
    };

    for tree in doc.event_trees.values() {
        note(&tree.initiating_event.message, &mut refs);
        for node in tree.nodes.values() {
            match node {
                Node::Operation(op) => {
                    if let Some(ref m) = op.emits {
                        note(m, &mut refs);
                    }
                }
                Node::Consequence(cons) => {
                    if let Some(ref m) = cons.message {
                        note(m, &mut refs);
                    }
                }
                _ => {}
            }
        }
    }

    if let Some(ref fault_trees) = doc.fault_trees {
        for ft in fault_trees.values() {
            if let Some(ref m) = ft.top_event.message {
                note(m, &mut refs);
            }
            for be in ft.basic_events.values() {
                if let Some(ref m) = be.message {
                    note(m, &mut refs);
                }
            }
        }
    }

    refs
}

fn ref_to_type_name(msg_ref: &MessageRef) -> String {
    let pointer = match msg_ref {
        MessageRef::External(r) => &r.pointer,
        MessageRef::Internal(r) => &r.pointer,
    };
    extract_last_segment(pointer)
}

fn extract_last_segment(pointer: &str) -> String {
    let last = pointer.rsplit('/').next().unwrap_or("Unknown");
    to_pascal_case(last)
}

fn generate_message_dataclass(type_name: &str, message: &serde_json::Value) -> String {
    let payload_type_name = format!("{type_name}Payload");
    let payload_schema = message.get("payload").cloned().unwrap_or(serde_json::Value::Null);

    let mut nested = String::new();
    let payload_py_type = schema_to_python_type(&payload_type_name, &payload_schema, &mut nested, false);

    let mut out = String::new();
    out.push_str(&nested);
    out.push_str("@dataclass\n");
    out.push_str(&format!("class {type_name}:\n"));
    out.push_str(&format!("    payload: {payload_py_type}\n"));
    out.push_str("    headers: dict[str, object] | None = None\n\n\n");
    out
}

/// Python analog of the Rust/Java target's struct/record generators, but
/// with one Python-specific constraint neither of those has: a
/// `@dataclass`'s fields without a default value must all precede fields
/// *with* a default, so (unlike the schema's own property order) required
/// fields are always emitted before optional ones.
fn generate_dataclass_from_schema(name: &str, schema: &serde_json::Value, output: &mut String) {
    let Some(properties) = schema.get("properties").and_then(|p| p.as_object()) else {
        return;
    };

    let required: std::collections::BTreeSet<&str> = schema
        .get("required")
        .and_then(|r| r.as_array())
        .map(|arr| arr.iter().filter_map(|v| v.as_str()).collect())
        .unwrap_or_default();

    let mut nested = String::new();
    let mut required_fields = Vec::new();
    let mut optional_fields = Vec::new();

    for (field_name, field_schema) in properties {
        let snake = to_snake_case(field_name);
        let nested_type_name = format!("{name}{}", to_pascal_case(field_name));
        let is_required = required.contains(field_name.as_str());
        let py_type = schema_to_python_type(&nested_type_name, field_schema, &mut nested, !is_required);
        if is_required {
            required_fields.push(format!("    {snake}: {py_type}\n"));
        } else {
            optional_fields.push(format!("    {snake}: {py_type} = None\n"));
        }
    }

    output.push_str(&nested);
    output.push_str("@dataclass\n");
    output.push_str(&format!("class {name}:\n"));
    if required_fields.is_empty() && optional_fields.is_empty() {
        output.push_str("    pass\n");
    } else {
        for f in &required_fields {
            output.push_str(f);
        }
        for f in &optional_fields {
            output.push_str(f);
        }
    }
    output.push_str("\n\n");
}

fn schema_to_python_type(
    candidate_name: &str,
    schema: &serde_json::Value,
    nested: &mut String,
    nullable: bool,
) -> String {
    let base = match schema.get("type").and_then(|t| t.as_str()) {
        Some("string") => "str".to_string(),
        Some("integer") => "int".to_string(),
        Some("number") => "float".to_string(),
        Some("boolean") => "bool".to_string(),
        Some("array") => {
            let item_type = match schema.get("items") {
                Some(items_schema) => schema_to_python_type(
                    &format!("{candidate_name}Item"),
                    items_schema,
                    nested,
                    true,
                ),
                None => "object".to_string(),
            };
            format!("list[{item_type}]")
        }
        Some("object") => {
            if schema.get("properties").is_some() {
                generate_dataclass_from_schema(candidate_name, schema, nested);
                candidate_name.to_string()
            } else {
                "dict[str, object]".to_string()
            }
        }
        _ => "object".to_string(),
    };
    if nullable {
        format!("{base} | None")
    } else {
        base
    }
}

