fn collect_message_refs(doc: &EtlDocument) -> BTreeMap<String, MessageRef> {
    let mut refs: BTreeMap<String, MessageRef> = BTreeMap::new();
    let note = |m: &MessageRef, refs: &mut BTreeMap<String, MessageRef>| {
        let name = ref_to_type_name(m);
        refs.entry(name).or_insert_with(|| m.clone());
    };

    for tree in doc.event_trees.values() {
        note(&tree.initiating_event.message, &mut refs);
        for node in tree.nodes.values() {
            match node {
                Node::Operation(op) => {
                    if let Some(ref m) = op.emits {
                        note(m, &mut refs);
                    }
                }
                Node::Consequence(cons) => {
                    if let Some(ref m) = cons.message {
                        note(m, &mut refs);
                    }
                }
                _ => {}
            }
        }
    }

    if let Some(ref fault_trees) = doc.fault_trees {
        for ft in fault_trees.values() {
            if let Some(ref m) = ft.top_event.message {
                note(m, &mut refs);
            }
            for be in ft.basic_events.values() {
                if let Some(ref m) = be.message {
                    note(m, &mut refs);
                }
            }
        }
    }

    refs
}

fn ref_to_type_name(msg_ref: &MessageRef) -> String {
    let pointer = match msg_ref {
        MessageRef::External(r) => &r.pointer,
        MessageRef::Internal(r) => &r.pointer,
    };
    extract_last_segment(pointer)
}

fn extract_last_segment(pointer: &str) -> String {
    let last = pointer.rsplit('/').next().unwrap_or("Unknown");
    to_pascal_case(last)
}

fn generate_message_record(type_name: &str, message: &serde_json::Value) -> String {
    let payload_type_name = format!("{type_name}Payload");
    let payload_schema = message.get("payload").cloned().unwrap_or(serde_json::Value::Null);

    let mut nested = String::new();
    let payload_cs_type = schema_to_dotnet_type(&payload_type_name, &payload_schema, &mut nested, false);

    let mut out = String::new();
    out.push_str(&nested);
    out.push_str(&format!(
        "public sealed record {type_name}({payload_cs_type} Payload, IReadOnlyDictionary<string, object>? Headers = null);\n\n"
    ));
    out
}

/// C# analog of the Rust/Java/Python targets' struct/record/dataclass
/// generators. Like the Python target (and unlike Java's `record`, whose
/// fields have no such constraint), a C# positional `record`'s
/// constructor parameters without a default must all precede parameters
/// *with* a default — so required fields are always emitted before
/// optional ones, regardless of the schema's own property order.
fn generate_record_from_schema(name: &str, schema: &serde_json::Value, output: &mut String) {
    let Some(properties) = schema.get("properties").and_then(|p| p.as_object()) else {
        return;
    };

    let required: std::collections::BTreeSet<&str> = schema
        .get("required")
        .and_then(|r| r.as_array())
        .map(|arr| arr.iter().filter_map(|v| v.as_str()).collect())
        .unwrap_or_default();

    let mut nested = String::new();
    let mut required_params = Vec::new();
    let mut optional_params = Vec::new();

    for (field_name, field_schema) in properties {
        let pascal = to_pascal_case(field_name);
        let nested_type_name = format!("{name}{pascal}");
        let is_required = required.contains(field_name.as_str());
        let cs_type = schema_to_dotnet_type(&nested_type_name, field_schema, &mut nested, !is_required);
        let json_attr = if pascal != *field_name {
            format!("[property: JsonPropertyName(\"{field_name}\")] ")
        } else {
            String::new()
        };
        if is_required {
            required_params.push(format!("{json_attr}{cs_type} {pascal}"));
        } else {
            optional_params.push(format!("{json_attr}{cs_type} {pascal} = default"));
        }
    }

    let mut params = required_params;
    params.extend(optional_params);

    output.push_str(&nested);
    output.push_str(&format!("public sealed record {name}({});\n\n", params.join(", ")));
}

fn schema_to_dotnet_type(
    candidate_name: &str,
    schema: &serde_json::Value,
    nested: &mut String,
    nullable: bool,
) -> String {
    let base = match schema.get("type").and_then(|t| t.as_str()) {
        Some("string") => "string".to_string(),
        Some("integer") => "long".to_string(),
        Some("number") => "double".to_string(),
        Some("boolean") => "bool".to_string(),
        Some("array") => {
            let item_type = match schema.get("items") {
                Some(items_schema) => schema_to_dotnet_type(
                    &format!("{candidate_name}Item"),
                    items_schema,
                    nested,
                    true,
                ),
                None => "object".to_string(),
            };
            return format!("IReadOnlyList<{item_type}>{}", if nullable { "?" } else { "" });
        }
        Some("object") => {
            if schema.get("properties").is_some() {
                generate_record_from_schema(candidate_name, schema, nested);
                candidate_name.to_string()
            } else {
                return format!(
                    "IReadOnlyDictionary<string, object>{}",
                    if nullable { "?" } else { "" }
                );
            }
        }
        _ => "object".to_string(),
    };
    if nullable {
        format!("{base}?")
    } else {
        base
    }
}

