//! The `dotnet` [`CodeGenerator`] target.
//!
//! Consumes the exact same validated [`EtlDocument`] + resolved fault-tree
//! probabilities + [`AsyncApiRegistry`] every other target consumes.
//! Nothing here re-parses `.etdl`, re-validates ECEL conditions, or
//! re-evaluates fault trees. Generated C# is a thin binding — modern
//! P/Invoke (`[LibraryImport]` + `[UnmanagedCallersOnly]`) to the same
//! compiled `etdl-runtime-ffi` C ABI the Java (`java.lang.foreign`) and
//! Python (`ctypes`) targets bind to — not a reimplementation of ETDL
//! semantics. See `docs/architecture/targets.md`.
//!
//! Building this crate never requires a .NET SDK — it only emits C#
//! source text (plus a minimal `.csproj`). A .NET SDK (8+, for
//! `LibraryImport`/`UnmanagedCallersOnly`) is needed only to *build and
//! run* the generated output, and `etdl-runtime-ffi`'s compiled shared
//! library is needed to run anything that touches
//! `BranchMonitor`/`RetryPolicy`/`Condition`.

use etdl_compiler::{CodeGenerator, Diagnostic, GeneratedFile};
use etdl_parser::ast::{
    BackoffStrategy as AstBackoffStrategy, ChannelRef, Condition, EtlDocument, EventTree,
    MessageRef, Node,
};
use etdl_parser::asyncapi::AsyncApiRegistry;
use etdl_parser::ecel;
use std::collections::BTreeMap;

pub struct DotnetCodeGenerator {
    pub version: String,
    /// C# namespace for document-specific output. `None` derives it
    /// (PascalCase) from `info.domain`.
    pub namespace: Option<String>,
}

impl Default for DotnetCodeGenerator {
    fn default() -> Self {
        Self::new()
    }
}

impl DotnetCodeGenerator {
    pub fn new() -> Self {
        DotnetCodeGenerator {
            version: env!("CARGO_PKG_VERSION").to_string(),
            namespace: None,
        }
    }

    fn resolve_namespace(&self, doc: &EtlDocument) -> String {
        if let Some(ref ns) = self.namespace {
            return ns.clone();
        }
        sanitize_namespace(&doc.info.domain)
    }
}

impl CodeGenerator for DotnetCodeGenerator {
    fn target_name(&self) -> &'static str {
        "dotnet"
    }

    fn generate_all(
        &self,
        doc: &EtlDocument,
        fault_tree_probs: &BTreeMap<String, f64>,
        registry: &AsyncApiRegistry,
        stem: &str,
        _diagnostics: &mut Vec<Diagnostic>,
    ) -> Result<Vec<GeneratedFile>, String> {
        let namespace = self.resolve_namespace(doc);
        let project_name = to_pascal_case(&sanitize_ident(stem));

        let mut files = runtime_files();
        files.push(GeneratedFile::new(
            format!("{project_name}.csproj"),
            generate_csproj(&project_name),
        ));

        let message_refs = collect_message_refs(doc);
        if !message_refs.is_empty() {
            let mut messages_file = String::new();
            messages_file.push_str("// AUTOGENERATED BY ETDL COMPILER - DO NOT EDIT DIRECTLY\n\n");
            messages_file.push_str("using System.Collections.Generic;\n");
            messages_file.push_str("using System.Text.Json.Serialization;\n\n");
            messages_file.push_str(&format!("namespace {namespace};\n\n"));
            for (type_name, msg_ref) in &message_refs {
                let value = registry
                    .resolve_message(doc, msg_ref)
                    .map_err(|e| format!("resolving message for '{type_name}': {e}"))?;
                messages_file.push_str(&generate_message_record(type_name, &value));
            }
            files.push(GeneratedFile::new(
                format!("{namespace}/Messages.cs"),
                messages_file,
            ));
        }

        for tree in doc.event_trees.values() {
            let tree_id = tree_id_of(doc, tree);
            let iface_name = format!("I{}Handlers", to_pascal_case(&sanitize_ident(tree_id)));
            let handler_methods = collect_handler_methods(tree);
            let msg_type = ref_to_type_name(&tree.initiating_event.message);
            files.push(GeneratedFile::new(
                format!("{namespace}/{iface_name}.cs"),
                generate_handlers_interface(&namespace, &iface_name, &msg_type, &handler_methods),
            ));
        }

        let workflow = generate_workflow_class(doc, &namespace, &project_name, fault_tree_probs)?;
        files.push(GeneratedFile::new(
            format!("{namespace}/{project_name}Workflow.cs"),
            workflow,
        ));

        Ok(files)
    }
}

fn tree_id_of<'a>(doc: &'a EtlDocument, tree: &EventTree) -> &'a str {
    doc.event_trees
        .iter()
        .find(|(_, t)| std::ptr::eq(*t, tree))
        .map(|(id, _)| id.as_str())
        .unwrap_or("Tree")
}

fn generate_csproj(project_name: &str) -> String {
    format!(
        r#"<!-- AUTOGENERATED BY ETDL COMPILER - safe to edit (project settings only; add your own
     developer .cs files anywhere under this directory and the SDK's default
     globbing picks them up automatically).

     TargetFramework: LibraryImport/UnmanagedCallersOnly (the P/Invoke
     mechanism etdl.runtime uses) need .NET 7+; net9.0 is picked because
     targeting any framework version other than the installed SDK's own
     major version makes the SDK download that version's runtime pack from
     NuGet on first build (slow, and unnecessary here). Change this if your
     SDK is a different major version. -->
<Project Sdk="Microsoft.NET.Sdk">

  <PropertyGroup>
    <OutputType>Exe</OutputType>
    <TargetFramework>net9.0</TargetFramework>
    <RootNamespace>{project_name}</RootNamespace>
    <ImplicitUsings>enable</ImplicitUsings>
    <Nullable>enable</Nullable>
    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
  </PropertyGroup>

</Project>
"#
    )
}

