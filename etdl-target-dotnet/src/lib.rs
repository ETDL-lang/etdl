fn collect_handler_methods(tree: &EventTree) -> Vec<String> {
    let mut seen = std::collections::BTreeSet::new();
    let mut methods = Vec::new();
    for node in tree.nodes.values() {
        if let Node::Operation(op) = node {
            let name = to_pascal_case(&op.handler);
            if seen.insert(name.clone()) {
                methods.push(name);
            }
        }
    }
    methods
}

fn generate_handlers_interface(namespace: &str, iface_name: &str, msg_type: &str, methods: &[String]) -> String {
    let mut out = String::new();
    out.push_str("// AUTOGENERATED BY ETDL COMPILER - DO NOT EDIT DIRECTLY\n");
    out.push_str("// Implement this interface in your own (never regenerated) class; the\n");
    out.push_str("// generated orchestration calls through it and never the other way around.\n");
    out.push_str(&format!("namespace {namespace};\n\n"));
    out.push_str(&format!("public interface {iface_name}\n{{\n"));
    for method in methods {
        out.push_str(&format!("    object? {method}({msg_type} message);\n"));
    }
    out.push_str("}\n");
    out
}

