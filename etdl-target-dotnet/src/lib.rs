/// The C# analog of `etdl_core::retry::RetryPolicy` — the attempt-count
/// and backoff *sequence* are computed once, in Rust
/// (`etdl_retry_policy_execute`'s native loop), via an
/// `[UnmanagedCallersOnly]` trampoline bound to `op` through a
/// `GCHandle`-pinned context object (the standard .NET idiom for passing
/// managed state through a static native callback). Per-attempt timeout
/// enforcement stays here (see `docs/architecture/targets.md`'s
/// "Ownership model": no FFI boundary can safely cancel foreign code
/// mid-flight) — note a .NET `Task` cannot be forcibly killed either, so a
/// "timed out" attempt's task still runs to completion in the background;
/// only the *retry loop* moves on.
const RETRY_POLICY_CS: &str = r#"// Read-only ETDL runtime. DO NOT EDIT DIRECTLY.
//
// Thin facade over the native `etdl_core::RetryPolicy` (via
// `etdl-runtime-ffi`'s callback-driven `etdl_retry_policy_execute`). Owns
// one native handle; always use with `using`.
namespace Etdl.Runtime;

using System;
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using System.Threading.Tasks;

public sealed class RetryPolicy : IDisposable
{
    private readonly nint _handle;
    private bool _disposed;

    public RetryPolicy(uint maxAttempts, ulong backoffMs, BackoffStrategy strategy)
    {
        _handle = NativeMethods.etdl_retry_policy_new(maxAttempts, backoffMs, (int)strategy);
        if (_handle == 0)
        {
            throw new InvalidOperationException($"etdl_retry_policy_new failed: {NativeMethods.LastError()}");
        }
    }

    /// <summary>Per-<see cref="Execute"/>-call state, reached from the
    /// static <see cref="NativeTrampoline"/> through a pinned
    /// <see cref="GCHandle"/> passed as the native call's <c>userData</c>.
    /// <c>op</c>'s own exception (checked <see cref="WorkflowError"/> or
    /// any other exception) is caught here — it never crosses the native
    /// call, exactly as the FFI boundary requires.</summary>
    private sealed class Trampoline
    {
        public required Func<object?> Op;
        public double? TimeoutSeconds;
        public object? Result;
        public WorkflowError? CheckedError;
        public Exception? UncheckedError;

        public int Invoke(uint attempt)
        {
            try
            {
                Task<object?> task = Task.Run(Op);
                bool completed = TimeoutSeconds is double t
                    ? task.Wait(TimeSpan.FromSeconds(t))
                    : task.Wait(-1);
                if (!completed)
                {
                    CheckedError = new WorkflowError($"operation timed out after {TimeoutSeconds}s");
                    return 1;
                }
                Result = task.Result;
                return 0;
            }
            catch (AggregateException ae) when (ae.InnerException is WorkflowError we)
            {
                CheckedError = we;
                return 1;
            }
            catch (AggregateException ae)
            {
                UncheckedError = ae.InnerException ?? ae;
                return -1;
            }
            catch (Exception e)
            {
                UncheckedError = e;
                return -1;
            }
        }
    }

    [UnmanagedCallersOnly(CallConvs = new[] { typeof(CallConvCdecl) })]
    private static int NativeTrampoline(nint userData, uint attempt)
    {
        GCHandle gcHandle = GCHandle.FromIntPtr(userData);
        var trampoline = (Trampoline)gcHandle.Target!;
        return trampoline.Invoke(attempt);
    }

    public unsafe T? Execute<T>(Func<T> op, double? timeoutSeconds = null)
    {
        var trampoline = new Trampoline { Op = () => op(), TimeoutSeconds = timeoutSeconds };
        GCHandle gcHandle = GCHandle.Alloc(trampoline);
        try
        {
            uint attemptsUsed;
            int rc = NativeMethods.etdl_retry_policy_execute(
                _handle, &NativeTrampoline, GCHandle.ToIntPtr(gcHandle), &attemptsUsed);

            if (rc == NativeMethods.RetryOk)
            {
                return (T?)trampoline.Result;
            }
            if (trampoline.UncheckedError != null)
            {
                throw trampoline.UncheckedError;
            }
            if (trampoline.CheckedError != null)
            {
                throw trampoline.CheckedError;
            }
            string kind = rc == NativeMethods.RetryFatal ? "retry failed fatally" : "retry exhausted";
            throw new WorkflowError($"{kind}: {NativeMethods.LastError()}");
        }
        finally
        {
            gcHandle.Free();
        }
    }

    public void Dispose()
    {
        if (!_disposed)
        {
            _disposed = true;
            NativeMethods.etdl_retry_policy_free(_handle);
        }
    }
}
"#;

/// The C# analog of `etdl_core::condition::{contains, matches}` — ECEL
/// `in`/`matches` semantics stay in Rust; this facade only marshals
/// values to/from the JSON text `etdl_condition_contains` expects, using
