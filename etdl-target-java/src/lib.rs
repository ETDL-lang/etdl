//! The `java` [`CodeGenerator`] target.
//!
//! Consumes the exact same validated [`EtlDocument`] + resolved fault-tree
//! probabilities + [`AsyncApiRegistry`] that [`etdl_compiler::RustCodeGenerator`]
//! consumes — nothing in this crate re-parses `.etdl`, re-validates ECEL
//! conditions, or re-evaluates fault trees. Only the code-generation layer
//! differs. See `docs/architecture/targets.md` for the full picture.
//!
//! Building this crate never requires a JDK — it only emits Java source
//! text. A JDK is needed solely to *compile the generated output*, which is
//! entirely the concern of whoever consumes the generated files.
//!
//! # Output shape
//!
//! - `etdl/runtime/*.java` — a small, fixed, read-only Java runtime
//!   (`WorkflowError`, `Publisher`, `BranchMonitor`, `RetryPolicy`,
//!   `BackoffStrategy`, `Condition`) mirroring the pieces of `etdl-core`
//!   every generated Rust file already depends on. Not document-specific;
//!   identical across every `--target java` invocation.
//! - `<package>/<Type>.java` — one record file per distinct AsyncAPI message
//!   referenced anywhere in the document (both External and Internal
//!   References resolve through [`AsyncApiRegistry::resolve_message`], so —
//!   unlike the Rust target — Java never assumes a pre-existing
//!   `{alias}::messages`-equivalent package exists for an External
//!   Reference; it generates the record either way).
//! - `<package>/<Stem>Workflow.java` — one `public final class` holding the
//!   fault-tree-probability constants and one `public static` orchestration
//!   method per event tree — the stable, read-only, autogenerated
//!   orchestration logic (branches, retries, SLA/branch monitoring, sends),
//!   structurally the same thing `RustCodeGenerator::generate_event_tree_handler`
//!   emits, translated to Java control flow.
//! - `<package>/<Tree>Handlers.java` — one `public interface` per event
//!   tree, one method per distinct `handler:` id used in that tree. This is
//!   the user-editable/application-specific boundary: the orchestration
//!   class calls through this interface, never the other way around, so a
//!   developer implements it in their own (never regenerated) class without
//!   ever touching the generated orchestration or runtime code — the same
//!   role Rust's naming-convention `async fn <handler>(...)` functions play,
//!   made explicit as a generated contract because Java has no equivalent
//!   free-function-by-convention mechanism.
//!
//! # Known scope limits (see the crate-level deliverables report)
//!
//! Generated Java carries no JSON library dependency (unlike the Rust
//! target, which bakes in `serde`/`serde_json`): message records are plain
//! data carriers and `Publisher.publish` takes `Object`. (De)serialization
//! across the wire is left to the integration layer the developer wires up,
//! so the generated output — and this crate's own compile-check test —
//! never require a JSON library to be on the classpath, only a JDK.

use etdl_compiler::{CodeGenerator, Diagnostic, GeneratedFile};
use etdl_parser::ast::{
    BackoffStrategy as AstBackoffStrategy, ChannelRef, Condition, EtlDocument, EventTree,
    MessageRef, Node,
};
use etdl_parser::asyncapi::AsyncApiRegistry;
use etdl_parser::ecel;
use std::collections::BTreeMap;

pub struct JavaCodeGenerator {
    pub version: String,
    /// Java package for document-specific output (`<package>/<Type>.java`,
    /// `<package>/<Stem>Workflow.java`, `<package>/<Tree>Handlers.java`).
    /// `None` derives it from `info.domain` (falling back to
    /// `etdl.generated` when that doesn't yield a usable package name).
    /// The fixed `etdl.runtime` package is never affected by this field.
    pub package: Option<String>,
}

impl Default for JavaCodeGenerator {
    fn default() -> Self {
        Self::new()
    }
}

impl JavaCodeGenerator {
    pub fn new() -> Self {
        JavaCodeGenerator {
            version: env!("CARGO_PKG_VERSION").to_string(),
            package: None,
        }
    }

    fn resolve_package(&self, doc: &EtlDocument) -> String {
        if let Some(ref p) = self.package {
            return p.clone();
        }
        sanitize_package(&doc.info.domain)
    }
}

impl CodeGenerator for JavaCodeGenerator {
    fn target_name(&self) -> &'static str {
        "java"
    }

    fn generate_all(
        &self,
        doc: &EtlDocument,
        fault_tree_probs: &BTreeMap<String, f64>,
        registry: &AsyncApiRegistry,
        stem: &str,
        _diagnostics: &mut Vec<Diagnostic>,
    ) -> Result<Vec<GeneratedFile>, String> {
        let package = self.resolve_package(doc);
        let package_dir = package.replace('.', "/");
        let class_stem = to_pascal_case(&sanitize_ident(stem));

        let mut files = runtime_files();

        let message_refs = collect_message_refs(doc);
        for (type_name, msg_ref) in &message_refs {
            let value = registry
                .resolve_message(doc, msg_ref)
                .map_err(|e| format!("resolving message for '{}': {}", type_name, e))?;
            let contents = generate_message_file(&package, type_name, &value);
            files.push(GeneratedFile::new(
                format!("{package_dir}/{type_name}.java"),
                contents,
            ));
        }

        for tree in doc.event_trees.values() {
            let tree_class = to_pascal_case(&sanitize_ident(tree_id_of(doc, tree)));
            let handlers_iface = format!("{tree_class}Handlers");
            let handler_methods = collect_handler_methods(tree);
            let msg_type = ref_to_type_name(&tree.initiating_event.message);

            files.push(GeneratedFile::new(
                format!("{package_dir}/{handlers_iface}.java"),
                generate_handlers_interface(&package, &handlers_iface, &msg_type, &handler_methods),
            ));
        }

        let workflow = generate_workflow_class(doc, &package, &class_stem, fault_tree_probs)?;
        files.push(GeneratedFile::new(
            format!("{package_dir}/{class_stem}Workflow.java"),
            workflow,
        ));

        Ok(files)
    }
}

fn tree_id_of<'a>(doc: &'a EtlDocument, tree: &EventTree) -> &'a str {
    doc.event_trees
        .iter()
        .find(|(_, t)| std::ptr::eq(*t, tree))
        .map(|(id, _)| id.as_str())
        .unwrap_or("Tree")
}

