/// `handler:` ids (core spec Section 5.5.2) used by every Operation node in
/// `tree`, deduplicated, in first-seen order. Every call site for a given
/// tree passes the same message type (the tree's initiating event message
/// type — codegen never rebinds `message` to a different type within a
/// tree), so one interface per tree, not per document, avoids any signature
/// collision between trees that happen to reuse a handler id with a
/// different message type.
fn collect_handler_methods(tree: &EventTree) -> Vec<String> {
    let mut seen = std::collections::BTreeSet::new();
    let mut methods = Vec::new();
    for node in tree.nodes.values() {
        if let Node::Operation(op) = node {
            let name = to_camel_case(&op.handler);
            if seen.insert(name.clone()) {
                methods.push(name);
            }
        }
    }
    methods
}

fn generate_handlers_interface(
    package: &str,
    iface_name: &str,
    msg_type: &str,
    methods: &[String],
) -> String {
    let mut out = String::new();
    out.push_str(&format!("package {package};\n\n"));
    out.push_str("import etdl.runtime.WorkflowError;\n\n");
    out.push_str("// AUTOGENERATED BY ETDL COMPILER - DO NOT EDIT DIRECTLY\n");
    out.push_str("// Implement this interface in your own (never regenerated) class; the\n");
    out.push_str("// generated orchestration in <Stem>Workflow calls through it and never the\n");
    out.push_str("// other way around.\n");
    out.push_str(&format!("public interface {iface_name} {{\n"));
    for method in methods {
        out.push_str(&format!(
            "    Object {method}({msg_type} message) throws WorkflowError;\n"
        ));
    }
    out.push_str("}\n");
    out
}

