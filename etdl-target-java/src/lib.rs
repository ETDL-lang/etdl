/// The native-binding layer: loads `libetdl_runtime_ffi` and exposes every
/// function from `etdl-runtime-ffi/src/lib.rs` as a `MethodHandle`, using
/// Java 21's (preview) Foreign Function & Memory API — no JNI glue code,
/// no per-language native crate, just a direct binding to the same plain C
/// ABI Go/.NET/Python bind to as well. `BranchMonitor`/`RetryPolicy`/
/// `Condition` are thin facades over this; nothing here re-implements ETDL
/// semantics — every method body is a native call plus argument/return
/// marshaling.
const ETDL_NATIVE_JAVA: &str = r#"package etdl.runtime;

import java.lang.foreign.Arena;
import java.lang.foreign.FunctionDescriptor;
import java.lang.foreign.Linker;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.SymbolLookup;
import java.lang.invoke.MethodHandle;

import static java.lang.foreign.ValueLayout.ADDRESS;
import static java.lang.foreign.ValueLayout.JAVA_BOOLEAN;
import static java.lang.foreign.ValueLayout.JAVA_DOUBLE;
import static java.lang.foreign.ValueLayout.JAVA_INT;
import static java.lang.foreign.ValueLayout.JAVA_LONG;

/**
 * Read-only ETDL runtime. DO NOT EDIT DIRECTLY.
 *
 * Binds to `libetdl_runtime_ffi` (built from the `etdl-runtime-ffi` Rust
 * crate — see `docs/architecture/targets.md`). Requires the JVM to run
 * with `--enable-preview --enable-native-access=ALL-UNNAMED` (Java 21's
 * Foreign Function & Memory API is a preview feature; it is finalized,
 * flag-free, in Java 22+).
 *
 * Library resolution order:
 * 1. system property `etdl.runtime.library` — an explicit absolute path
 *    to the shared library (`libetdl_runtime_ffi.so`/`.dylib`,
 *    `etdl_runtime_ffi.dll`).
 * 2. `System.loadLibrary("etdl_runtime_ffi")` — standard JVM native
 *    library search (`-Djava.library.path=...`, or the platform's usual
 *    shared-library search path).
 */
final class EtdlNative {
    private EtdlNative() {}

    // Mirrors etdl-runtime-ffi's ETDL_OK / ETDL_ERR_* / ETDL_RETRY_* constants exactly.
    static final int OK = 0;
    static final int ERR_NULL_HANDLE = -1;
    static final int ERR_INVALID_ARG = -2;
    static final int RETRY_OK = 0;
    static final int RETRY_EXHAUSTED = 1;
    static final int RETRY_FATAL = 2;

    private static final Linker LINKER = Linker.nativeLinker();
    private static final SymbolLookup LOOKUP = load();

    static final MethodHandle ABI_VERSION =
            handle("etdl_runtime_abi_version", FunctionDescriptor.of(JAVA_INT));
    static final MethodHandle LAST_ERROR_MESSAGE =
            handle("etdl_last_error_message", FunctionDescriptor.of(ADDRESS));
    static final MethodHandle STRING_FREE =
            handle("etdl_string_free", FunctionDescriptor.ofVoid(ADDRESS));
    static final MethodHandle BRANCH_MONITOR_NEW =
            handle("etdl_branch_monitor_new", FunctionDescriptor.of(ADDRESS, ADDRESS));
    static final MethodHandle BRANCH_MONITOR_FREE =
            handle("etdl_branch_monitor_free", FunctionDescriptor.ofVoid(ADDRESS));
    static final MethodHandle BRANCH_MONITOR_RECORD_BRANCH = handle(
            "etdl_branch_monitor_record_branch",
            FunctionDescriptor.of(JAVA_INT, ADDRESS, ADDRESS, JAVA_DOUBLE));
    static final MethodHandle BRANCH_MONITOR_RECORD_SUCCESS = handle(
            "etdl_branch_monitor_record_success",
            FunctionDescriptor.of(JAVA_INT, ADDRESS, ADDRESS, JAVA_DOUBLE, JAVA_BOOLEAN));
    static final MethodHandle BRANCH_MONITOR_RECORD_FAILURE = handle(
            "etdl_branch_monitor_record_failure",
            FunctionDescriptor.of(JAVA_INT, ADDRESS, ADDRESS, ADDRESS, JAVA_DOUBLE, JAVA_BOOLEAN));
    static final MethodHandle RETRY_POLICY_NEW = handle(
            "etdl_retry_policy_new",
            FunctionDescriptor.of(ADDRESS, JAVA_INT, JAVA_LONG, JAVA_INT));
    static final MethodHandle RETRY_POLICY_FREE =
            handle("etdl_retry_policy_free", FunctionDescriptor.ofVoid(ADDRESS));
    static final MethodHandle RETRY_POLICY_EXECUTE = handle(
            "etdl_retry_policy_execute",
            FunctionDescriptor.of(JAVA_INT, ADDRESS, ADDRESS, ADDRESS, ADDRESS));
    static final MethodHandle CONDITION_MATCHES =
            handle("etdl_condition_matches", FunctionDescriptor.of(JAVA_INT, ADDRESS, ADDRESS));
    static final MethodHandle CONDITION_CONTAINS =
            handle("etdl_condition_contains", FunctionDescriptor.of(JAVA_INT, ADDRESS, ADDRESS));

    private static SymbolLookup load() {
        String explicitPath = System.getProperty("etdl.runtime.library");
        if (explicitPath != null) {
            return SymbolLookup.libraryLookup(explicitPath, Arena.global());
        }
        String mappedName = System.mapLibraryName("etdl_runtime_ffi");
        try {
            System.loadLibrary("etdl_runtime_ffi");
        } catch (UnsatisfiedLinkError e) {
            throw new UnsatisfiedLinkError(
                    "could not load the ETDL Rust runtime ('" + mappedName + "'). Build it with "
                            + "`cargo build -p etdl-runtime-ffi --release` and either put its "
                            + "output directory on -Djava.library.path=..., or point "
                            + "-Detdl.runtime.library=<absolute path to " + mappedName
                            + "> directly at the file. Original error: " + e.getMessage());
        }
        return SymbolLookup.loaderLookup();
    }

    private static MethodHandle handle(String name, FunctionDescriptor descriptor) {
        MemorySegment symbol = LOOKUP.find(name).orElseThrow(() -> new UnsatisfiedLinkError(
                "symbol not found in the ETDL Rust runtime: " + name
                        + " (etdl-runtime-ffi version mismatch?)"));
        return LINKER.downcallHandle(symbol, descriptor);
    }

    /** The native ABI version (`etdl_runtime_abi_version()`), for diagnostics. */
    static int abiVersion() {
        return invokeInt(ABI_VERSION);
    }

    /**
     * Reads and frees the calling thread's last native error message (see
     * `etdl_last_error_message`/`etdl_string_free`), or a fallback string
     * if none is set.
     */
    static String lastError() {
        try {
            MemorySegment ptr = (MemorySegment) LAST_ERROR_MESSAGE.invokeWithArguments();
            if (MemorySegment.NULL.equals(ptr)) {
                return "(no further detail available from the native runtime)";
            }
            String message = ptr.reinterpret(4096).getUtf8String(0);
            STRING_FREE.invokeWithArguments(ptr);
            return message;
        } catch (Throwable t) {
            return "(failed to read native error message: " + t + ")";
        }
    }

    static MemorySegment cString(Arena arena, String s) {
        return arena.allocateUtf8String(s);
    }

    static int invokeInt(MethodHandle mh, Object... args) {
        try {
            return (int) mh.invokeWithArguments(args);
        } catch (Throwable t) {
            throw new RuntimeException("native ETDL runtime call failed: " + t.getMessage(), t);
        }
    }

    static MemorySegment invokeAddress(MethodHandle mh, Object... args) {
        try {
            return (MemorySegment) mh.invokeWithArguments(args);
        } catch (Throwable t) {
            throw new RuntimeException("native ETDL runtime call failed: " + t.getMessage(), t);
        }
    }

    static void invokeVoid(MethodHandle mh, Object... args) {
        try {
            mh.invokeWithArguments(args);
        } catch (Throwable t) {
            throw new RuntimeException("native ETDL runtime call failed: " + t.getMessage(), t);
        }
    }

    /**
     * Builds a native-callable upcall stub for `target` — the mechanism
     * {@link RetryPolicy#execute} uses to let `etdl_retry_policy_execute`'s
     * native loop call back into Java per attempt. `arena`-scoped: the stub
     * is only valid for `arena`'s lifetime, matching a single `execute`
     * call.
     */
    static MemorySegment upcallStub(MethodHandle target, FunctionDescriptor descriptor, Arena arena) {
        return LINKER.upcallStub(target, descriptor, arena);
    }
}
"#;

/// The Java analog of `etdl_core::BranchMonitor` — but not a
/// reimplementation of it: every method here is a direct call into the
/// same `BranchMonitor` the Rust target's generated code has always used,
/// via `etdl-runtime-ffi`. SLA anomaly detection, chaos injection, and
/// observation emission all happen exactly once, in Rust, for every
/// language target alike.
const BRANCH_MONITOR_JAVA: &str = r#"package etdl.runtime;

import java.lang.foreign.Arena;
import java.lang.foreign.MemorySegment;

/**
 * Read-only ETDL runtime. DO NOT EDIT DIRECTLY.
 *
 * Thin facade over the native `etdl_core::BranchMonitor` (via
 * `etdl-runtime-ffi`). Owns one native handle; always use in
 * try-with-resources (generated orchestration code always does) so
 * `etdl_branch_monitor_free` runs deterministically.
 */
public final class BranchMonitor implements AutoCloseable {
    private final Arena arena = Arena.ofConfined();
    private final MemorySegment handle;
    private boolean closed = false;

    public BranchMonitor(String nodeId) {
        MemorySegment nodeIdSeg = EtdlNative.cString(arena, nodeId);
        this.handle = EtdlNative.invokeAddress(EtdlNative.BRANCH_MONITOR_NEW, nodeIdSeg);
        if (MemorySegment.NULL.equals(this.handle)) {
            arena.close();
            throw new IllegalStateException(
                    "etdl_branch_monitor_new failed: " + EtdlNative.lastError());
        }
    }

    public void recordBranch(String outcome, double probability) {
        try (Arena call = Arena.ofConfined()) {
            MemorySegment outcomeSeg = EtdlNative.cString(call, outcome);
            int rc = EtdlNative.invokeInt(
                    EtdlNative.BRANCH_MONITOR_RECORD_BRANCH, handle, outcomeSeg, probability);
            checkRc(rc, "etdl_branch_monitor_record_branch");
        }
    }

    /** `probability` may be `null` when the operation has no linked fault tree. */
    public void recordSuccess(String operationId, Double probability) {
        try (Arena call = Arena.ofConfined()) {
            MemorySegment opSeg = EtdlNative.cString(call, operationId);
            int rc = EtdlNative.invokeInt(
                    EtdlNative.BRANCH_MONITOR_RECORD_SUCCESS,
                    handle, opSeg, probability == null ? 0.0 : probability, probability != null);
            checkRc(rc, "etdl_branch_monitor_record_success");
        }
    }

    /** `probability` may be `null` when the operation has no linked fault tree. */
    public void recordFailure(String operationId, Throwable error, Double probability) {
        try (Arena call = Arena.ofConfined()) {
            MemorySegment opSeg = EtdlNative.cString(call, operationId);
            MemorySegment errSeg = EtdlNative.cString(call, String.valueOf(error.getMessage()));
            int rc = EtdlNative.invokeInt(
                    EtdlNative.BRANCH_MONITOR_RECORD_FAILURE,
                    handle, opSeg, errSeg, probability == null ? 0.0 : probability, probability != null);
            checkRc(rc, "etdl_branch_monitor_record_failure");
        }
    }

    private void checkRc(int rc, String call) {
        if (rc != EtdlNative.OK) {
            throw new RuntimeException(call + " failed (code " + rc + "): " + EtdlNative.lastError());
        }
    }

    @Override
    public void close() {
        if (!closed) {
            closed = true;
            EtdlNative.invokeVoid(EtdlNative.BRANCH_MONITOR_FREE, handle);
            arena.close();
        }
    }
}
"#;

/// The Java analog of `etdl_core::retry::RetryPolicy` — the attempt-count
/// and backoff *sequence* are computed once, in Rust
/// (`etdl_retry_policy_execute`'s native loop), via a callback bound to
/// `op`. Per-attempt timeout enforcement stays here (see
/// `docs/architecture/targets.md`'s "Ownership model": no FFI boundary can
/// safely cancel foreign code mid-flight), using a virtual-thread executor
/// exactly like this class did before it called into Rust at all.
const RETRY_POLICY_JAVA: &str = r#"package etdl.runtime;

import java.lang.foreign.Arena;
import java.lang.foreign.FunctionDescriptor;
import java.lang.foreign.MemorySegment;
import java.lang.invoke.MethodHandle;
import java.lang.invoke.MethodHandles;
import java.lang.invoke.MethodType;
import java.util.concurrent.ExecutionException;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.TimeoutException;

import static java.lang.foreign.ValueLayout.ADDRESS;
import static java.lang.foreign.ValueLayout.JAVA_INT;

/**
 * Read-only ETDL runtime. DO NOT EDIT DIRECTLY.
 *
 * Thin facade over the native `etdl_core::RetryPolicy` (via
 * `etdl-runtime-ffi`'s callback-driven `etdl_retry_policy_execute`). Owns
 * one native handle; always use in try-with-resources.
 */
public final class RetryPolicy implements AutoCloseable {
    @FunctionalInterface
    public interface Op<T> {
        T call() throws WorkflowError;
    }

    private final Arena arena = Arena.ofConfined();
    private final MemorySegment handle;
    private boolean closed = false;

    public RetryPolicy(int maxAttempts, long backoffMs, BackoffStrategy strategy) {
        MemorySegment h = EtdlNative.invokeAddress(
                EtdlNative.RETRY_POLICY_NEW, maxAttempts, backoffMs, strategy.nativeValue());
        if (MemorySegment.NULL.equals(h)) {
            arena.close();
            throw new IllegalStateException("etdl_retry_policy_new failed: " + EtdlNative.lastError());
        }
        this.handle = h;
    }

    /**
     * Trampoline bound (per `execute` call, via {@link MethodHandles.Lookup#bind})
     * to a native upcall stub — this is what `etdl_retry_policy_execute`'s
     * `attempt` loop actually calls back into on every attempt. Runs `op`
     * under `timeoutMs`; its return value is the contract
     * `etdl_retry_policy_execute` documents: `0` success, positive
     * retryable, negative fatal. `op`'s own exception (checked
     * `WorkflowError` or any unchecked exception) is caught here — it never
     * escapes back across the native call, exactly as the FFI boundary
     * requires.
     */
    private final class Trampoline {
        private final Op<?> op;
        private final long timeoutMs;
        Object result;
        WorkflowError checkedError;
        RuntimeException uncheckedError;

        Trampoline(Op<?> op, long timeoutMs) {
            this.op = op;
            this.timeoutMs = timeoutMs;
        }

        @SuppressWarnings("unused") // invoked only via the bound MethodHandle below
        int invoke(MemorySegment userData, int attempt) {
            try (ExecutorService executor = Executors.newVirtualThreadPerTaskExecutor()) {
                Future<?> future = executor.submit(op::call);
                try {
                    result = future.get(timeoutMs, TimeUnit.MILLISECONDS);
                    return 0;
                } catch (TimeoutException te) {
                    future.cancel(true);
                    checkedError = new WorkflowError("operation timed out after " + timeoutMs + "ms", te);
                    return 1;
                } catch (ExecutionException ee) {
                    Throwable cause = ee.getCause();
                    if (cause instanceof WorkflowError we) {
                        checkedError = we;
                        return 1;
                    }
                    uncheckedError = (cause instanceof RuntimeException re) ? re : new RuntimeException(cause);
                    return -1;
                }
            } catch (InterruptedException ie) {
                Thread.currentThread().interrupt();
                uncheckedError = new RuntimeException(ie);
                return -1;
            } catch (RuntimeException re) {
                // Defensive: a panic-equivalent from `op` itself escaping the
                // executor submission path, not just its Future. Never let it
                // propagate through the native call.
                uncheckedError = re;
                return -1;
            }
        }
    }

    public <T> T execute(Op<T> op, long timeoutMs) throws WorkflowError {
        Trampoline trampoline = new Trampoline(op, timeoutMs);
        MethodHandle bound;
        try {
            bound = MethodHandles.lookup().bind(
                    trampoline, "invoke", MethodType.methodType(int.class, MemorySegment.class, int.class));
        } catch (ReflectiveOperationException e) {
            throw new AssertionError("Trampoline.invoke signature must match the callback descriptor", e);
        }

        try (Arena call = Arena.ofConfined()) {
            MemorySegment callbackStub = EtdlNative.upcallStub(
                    bound, FunctionDescriptor.of(JAVA_INT, ADDRESS, JAVA_INT), call);
            MemorySegment outAttempts = call.allocate(JAVA_INT);
            int rc = EtdlNative.invokeInt(
                    EtdlNative.RETRY_POLICY_EXECUTE, handle, callbackStub, MemorySegment.NULL, outAttempts);

            if (rc == EtdlNative.RETRY_OK) {
                @SuppressWarnings("unchecked")
                T result = (T) trampoline.result;
                return result;
            }
            if (trampoline.uncheckedError != null) {
                throw trampoline.uncheckedError;
            }
            if (trampoline.checkedError != null) {
                throw trampoline.checkedError;
            }
            throw new WorkflowError(
                    (rc == EtdlNative.RETRY_FATAL ? "retry failed fatally" : "retry exhausted")
                            + ": " + EtdlNative.lastError());
        }
    }

    @Override
    public void close() {
        if (!closed) {
            closed = true;
            EtdlNative.invokeVoid(EtdlNative.RETRY_POLICY_FREE, handle);
            arena.close();
        }
    }
}
"#;

/// The Java analog of `etdl_core::condition::{contains, matches}` — ECEL
/// `in`/`matches` semantics (RE2-compatible regex, set membership) stay in
/// Rust; this facade only marshals `List`/scalar values to the JSON text
/// `etdl_condition_contains` expects (a small, dependency-free encoder —
/// see its doc comment for why generated Java carries no JSON library).
const CONDITION_JAVA: &str = r#"package etdl.runtime;

import java.lang.foreign.Arena;
import java.lang.foreign.MemorySegment;
import java.util.List;

/**
 * Read-only ETDL runtime. DO NOT EDIT DIRECTLY.
 *
 * ECEL (core spec Section 6) `in`/`matches` operators lower to these
 * helpers, delegating to the native `etdl_core::condition` module (via
 * `etdl-runtime-ffi`) — so a `matches` regex or an `in` membership check
 * behaves byte-for-byte identically no matter which target (Rust, Java,
 * Python, Go, .NET) evaluates it.
 */
public final class Condition {
    private Condition() {}

    public static boolean matches(String value, String pattern) {
        try (Arena arena = Arena.ofConfined()) {
            MemorySegment valueSeg = EtdlNative.cString(arena, value == null ? "" : value);
            MemorySegment patternSeg = EtdlNative.cString(arena, pattern);
            int rc = EtdlNative.invokeInt(EtdlNative.CONDITION_MATCHES, valueSeg, patternSeg);
            if (rc < 0) {
                throw new IllegalArgumentException("etdl_condition_matches: " + EtdlNative.lastError());
            }
            return rc == 1;
        }
    }

    public static boolean contains(List<?> haystack, Object needle) {
        try (Arena arena = Arena.ofConfined()) {
            MemorySegment needleSeg = EtdlNative.cString(arena, toJsonScalar(needle));
            MemorySegment haystackSeg = EtdlNative.cString(arena, toJsonArray(haystack));
            int rc = EtdlNative.invokeInt(EtdlNative.CONDITION_CONTAINS, needleSeg, haystackSeg);
            if (rc < 0) {
                throw new IllegalArgumentException("etdl_condition_contains: " + EtdlNative.lastError());
            }
            return rc == 1;
        }
    }

    /**
     * A minimal, dependency-free JSON array encoder — deliberately not a
     * general-purpose JSON library, only what ECEL `in`'s scalar-typed
     * elements (string/number/boolean/null) need to reach
     * `etdl_condition_contains`'s JSON-text wire format.
     */
    private static String toJsonArray(List<?> items) {
        StringBuilder sb = new StringBuilder("[");
        if (items != null) {
            for (int i = 0; i < items.size(); i++) {
                if (i > 0) {
                    sb.append(',');
                }
                sb.append(toJsonScalar(items.get(i)));
            }
        }
        return sb.append(']').toString();
    }

    private static String toJsonScalar(Object value) {
        if (value == null) {
            return "null";
        }
        if (value instanceof Boolean || value instanceof Number) {
            return value.toString();
        }
        return '"' + escapeJsonString(value.toString()) + '"';
    }

    private static String escapeJsonString(String s) {
        StringBuilder sb = new StringBuilder(s.length() + 8);
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            switch (c) {
                case '"' -> sb.append("\\\"");
                case '\\' -> sb.append("\\\\");
                case '\n' -> sb.append("\\n");
                case '\r' -> sb.append("\\r");
                case '\t' -> sb.append("\\t");
                default -> {
                    if (c < 0x20) {
                        sb.append(String.format("\\u%04x", (int) c));
                    } else {
                        sb.append(c);
                    }
                }
            }
        }
        return sb.toString();
    }
}
"#;

