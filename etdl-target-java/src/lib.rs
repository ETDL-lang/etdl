/// Every distinct message type referenced anywhere in `doc`, keyed by the
/// Java type name it will generate as (same naming rule as
/// `RustCodeGenerator::ref_to_rust_type`: PascalCase of the reference
/// pointer's last segment, which for an Internal Reference is the
/// `components.messages.<id>` id). Unlike
/// `RustCodeGenerator::collect_internal_message_ids`, this collects BOTH
/// External and Internal References — the Java target has no equivalent of
/// Rust's assumed pre-existing `{alias}::messages` crate, so every message
/// actually used gets a real generated record, resolved through `registry`
/// either way (see `AsyncApiRegistry::resolve_message`).
fn collect_message_refs(doc: &EtlDocument) -> BTreeMap<String, MessageRef> {
    let mut refs: BTreeMap<String, MessageRef> = BTreeMap::new();
    let note = |m: &MessageRef, refs: &mut BTreeMap<String, MessageRef>| {
        let name = ref_to_type_name(m);
        refs.entry(name).or_insert_with(|| m.clone());
    };

    for tree in doc.event_trees.values() {
        note(&tree.initiating_event.message, &mut refs);
        for node in tree.nodes.values() {
            match node {
                Node::Operation(op) => {
                    if let Some(ref m) = op.emits {
                        note(m, &mut refs);
                    }
                }
                Node::Consequence(cons) => {
                    if let Some(ref m) = cons.message {
                        note(m, &mut refs);
                    }
                }
                _ => {}
            }
        }
    }

    if let Some(ref fault_trees) = doc.fault_trees {
        for ft in fault_trees.values() {
            if let Some(ref m) = ft.top_event.message {
                note(m, &mut refs);
            }
            for be in ft.basic_events.values() {
                if let Some(ref m) = be.message {
                    note(m, &mut refs);
                }
            }
        }
    }

    refs
}

fn ref_to_type_name(msg_ref: &MessageRef) -> String {
    let pointer = match msg_ref {
        MessageRef::External(r) => &r.pointer,
        MessageRef::Internal(r) => &r.pointer,
    };
    extract_last_segment(pointer)
}

fn extract_last_segment(pointer: &str) -> String {
    let last = pointer.rsplit('/').next().unwrap_or("Unknown");
    to_pascal_case(last)
}

/// Generates the `<package>/<TypeName>.java` file for one resolved AsyncAPI
/// Message Object value (`{name?, payload, headers?}`, the same envelope
/// shape `AsyncApiRegistry::resolve_message` normalizes both reference
/// kinds into). The envelope record (`public`, matching the filename) is
/// emitted last; the payload record and any nested-object records it needs
/// are emitted above it as package-private top-level records in the same
/// file — Java permits any number of non-public top-level types per file,
/// only one `public` type, which must match the filename.
fn generate_message_file(package: &str, type_name: &str, message: &serde_json::Value) -> String {
    let payload_type_name = format!("{type_name}Payload");
    let payload_schema = message.get("payload").cloned().unwrap_or(serde_json::Value::Null);

    let mut nested = String::new();
    let payload_java_type = schema_to_java_type(&payload_type_name, &payload_schema, &mut nested, false);

    let mut out = String::new();
    out.push_str(&format!("package {package};\n\n"));
    out.push_str("import java.util.List;\nimport java.util.Map;\n\n");
    out.push_str("// AUTOGENERATED BY ETDL COMPILER - DO NOT EDIT DIRECTLY\n\n");
    out.push_str(&nested);
    out.push_str(&format!(
        "public record {type_name}({payload_java_type} payload, Map<String, Object> headers) {{}}\n"
    ));
    out
}

/// Java analog of `RustCodeGenerator::generate_struct_from_schema`: emits a
/// package-private `record <name>(...)` for an object-typed JSON Schema. A
/// schema with no `properties` (or a non-object schema) falls back to
/// `Map<String, Object>` at the call site instead — unlike the Rust target's
/// always-present newtype wrapper, Java has no ceremony-free equivalent, and
/// a bare `Map` is idiomatic enough for a schema too loose to model.
fn generate_record_from_schema(name: &str, schema: &serde_json::Value, output: &mut String) {
    let Some(properties) = schema.get("properties").and_then(|p| p.as_object()) else {
        return;
    };

    let required: std::collections::BTreeSet<&str> = schema
        .get("required")
        .and_then(|r| r.as_array())
        .map(|arr| arr.iter().filter_map(|v| v.as_str()).collect())
        .unwrap_or_default();

    let mut nested = String::new();
    let mut components = Vec::new();

    for (field_name, field_schema) in properties {
        let camel = to_camel_case(field_name);
        let nested_type_name = format!("{name}{}", to_pascal_case(field_name));
        let is_required = required.contains(field_name.as_str());
        let java_type = schema_to_java_type(&nested_type_name, field_schema, &mut nested, !is_required);
        components.push(format!("{java_type} {camel}"));
    }

    output.push_str(&nested);
    output.push_str(&format!("record {name}({}) {{}}\n\n", components.join(", ")));
}

/// Java analog of `RustCodeGenerator::schema_to_rust_type`. `nullable`
/// requests a boxed wrapper for a JSON Schema primitive (Java has no
/// primitive `Option<T>`-equivalent; a non-required field becomes a
/// nullable boxed type instead, the idiomatic Java equivalent).
fn schema_to_java_type(
    candidate_name: &str,
    schema: &serde_json::Value,
    nested: &mut String,
    nullable: bool,
) -> String {
    match schema.get("type").and_then(|t| t.as_str()) {
        Some("string") => "String".to_string(),
        Some("integer") => if nullable { "Long" } else { "long" }.to_string(),
        Some("number") => if nullable { "Double" } else { "double" }.to_string(),
        Some("boolean") => if nullable { "Boolean" } else { "boolean" }.to_string(),
        Some("array") => {
            let item_type = match schema.get("items") {
                Some(items_schema) => schema_to_java_type(
                    &format!("{candidate_name}Item"),
                    items_schema,
                    nested,
                    true,
                ),
                None => "Object".to_string(),
            };
            format!("List<{item_type}>")
        }
        Some("object") => {
            if schema.get("properties").is_some() {
                generate_record_from_schema(candidate_name, schema, nested);
                candidate_name.to_string()
            } else {
                "Map<String, Object>".to_string()
            }
        }
        _ => "Object".to_string(),
    }
}

