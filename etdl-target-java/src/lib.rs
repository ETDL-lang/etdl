fn sanitize_package(domain: &str) -> String {
    let segments: Vec<String> = domain
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|s| !s.is_empty())
        .map(|s| {
            let lower = s.to_ascii_lowercase();
            if lower.chars().next().map(|c| c.is_ascii_digit()).unwrap_or(false) {
                format!("_{lower}")
            } else {
                lower
            }
        })
        .collect();

    if segments.is_empty() {
        "etdl.generated".to_string()
    } else {
        segments.join(".")
    }
}

fn sanitize_ident(s: &str) -> String {
    let cleaned: String = s
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    if cleaned.chars().next().map(|c| c.is_ascii_digit()).unwrap_or(true) {
        format!("_{cleaned}")
    } else {
        cleaned
    }
}

fn to_snake_case(s: &str) -> String {
    let mut result = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 {
                result.push('_');
            }
            result.push(c.to_lowercase().next().unwrap());
        } else {
            result.push(c);
        }
    }
    result
}

fn to_upper_snake(s: &str) -> String {
    to_snake_case(s).to_uppercase()
}

fn to_pascal_case(s: &str) -> String {
    let mut result = String::new();
    let mut capitalize = true;
    for c in s.chars() {
        if c == '_' || c == '-' || c == ' ' {
            capitalize = true;
        } else if capitalize {
            result.extend(c.to_uppercase());
            capitalize = false;
        } else {
            result.push(c);
        }
    }
    result
}

fn to_camel_case(s: &str) -> String {
    let pascal = to_pascal_case(s);
    let mut chars = pascal.chars();
    match chars.next() {
        Some(c) => c.to_lowercase().collect::<String>() + chars.as_str(),
        None => String::new(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn package_sanitizes_domain() {
        assert_eq!(sanitize_package("com.example.orders"), "com.example.orders");
        assert_eq!(sanitize_package(""), "etdl.generated");
        assert_eq!(sanitize_package("Order-Fulfillment"), "order.fulfillment");
    }

    #[test]
    fn camel_and_pascal_case() {
        assert_eq!(to_pascal_case("order_placed"), "OrderPlaced");
        assert_eq!(to_camel_case("order_placed"), "orderPlaced");
        assert_eq!(to_camel_case("HandlerName"), "handlerName");
    }

    #[test]
    fn in_operator_lowers_to_condition_contains() {
        let cond = ecel::parse_condition(
            "message.payload.status in [\"PAID\", \"AUTHORIZED\"]",
        )
        .unwrap();
        let code = condition_to_java_code(&cond);
        assert!(code.contains("etdl.runtime.Condition.contains"), "got: {code}");
        assert!(code.contains("\"PAID\""));
    }

    #[test]
    fn matches_operator_lowers_to_condition_matches() {
        let cond = ecel::parse_condition(
            "message.payload.reference matches \"^ORD-[0-9]{8}$\"",
        )
        .unwrap();
        let code = condition_to_java_code(&cond);
        assert!(code.contains("etdl.runtime.Condition.matches"), "got: {code}");
    }

    #[test]
    fn comparison_uses_record_accessors() {
        let cond = ecel::parse_condition("message.payload.amount >= 10000").unwrap();
        let code = condition_to_java_code(&cond);
        assert_eq!(code, "message.payload().amount() >= 10000");
    }
}
